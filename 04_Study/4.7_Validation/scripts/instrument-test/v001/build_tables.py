HEAD = r'% Generated by 04_Study/4.7_Validation/scripts/instrument-test/v001/build_tables.py; do not edit.' + '\n'
ORIGIN = {'core': r'\ocore', 'context': r'\octx', 'implementation': r'\oimp', 'external': r'\oext'}
RUN_LLM = 'llm'


def tex(text):
    """Escape plain text for LaTeX."""
    for a, b in (('\\', r'\textbackslash{}'), ('&', r'\&'), ('%', r'\%'), ('_', r'\_'), ('#', r'\#'),
                 ('$', r'\$')):
        text = text.replace(a, b)
    return text


def node(model, code):
    if code in model['components']:
        return ORIGIN[model['components'][code]['origin']] + '{' + code + '}'
    return code


def expression(model, expr):
    """A readable, coloured form of a tree expression."""
    if isinstance(expr, str):
        return node(model, expr)
    (op, children), = expr.items()
    word = {'and': ' AND ', 'or': ' OR ', 'orplus': ' OR+ '}[op]
    parts = [('(' + expression(model, c) + ')') if isinstance(c, dict) else expression(model, c)
             for c in children]
    return word.join(parts)


def cite(source):
    """'key p. 5' -> \\cite[p.~5]{key}."""
    key, _, rest = source.partition(' ')
    return r'\parencite[' + rest.replace(' ', '~') + ']{' + key + '}'


def mentions(llm, standin, review):
    """{(unit, node): set of statuses} after the review rule."""
    units = load_units(llm)
    runs = [compare.stage1_labels(load_stage1(llm, 'stage1', r), units) for r in compare.RUNS]
    votes = Counter(label for run in runs for label in run)
    out = {}
    for label, n in votes.items():
        if n >= 2:
            statuses = Counter(run[label].get('status') for run in runs if label in run)
            out[label] = {statuses.most_common(1)[0][0][0]}
    for unit, row in standin.items():
        for item in (row.get('n') or []) + (row.get('h') or []):
            code, status = item.split(':')
            out.setdefault((unit, code), set()).add(status)
    for rej in review['rejected_mentions']:
        out.pop((rej['unit'], rej['node']), None)
    return out


def coverage(model, mentions_on_surface, harm, path):
    """(level, denied) of one pathway on one surface."""
    cap = model['capabilities'][path['capability']]
    def statuses(code):
        return mentions_on_surface.get(code, set())
    if statuses(harm) - {'d'}:
        return 3, False
    cap_status = statuses(path['capability'])
    denied = 'd' in cap_status
    if cap_status - {'d'}:
        return 2, denied
    leaves = ev.leaves(cap['needs'])
    comp = [c for c in leaves if statuses(c) - {'d'}]
    leaf_denied = any('d' in statuses(c) for c in leaves)
    return (1 if comp else 0), (denied or (leaf_denied and not comp))


SHADE = {0: r'\cellcolor{white}', 1: r'\cellcolor{primary!15}', 2: r'\cellcolor{primary!40}',
         3: r'\cellcolor{primary}\color{white}'}
STATE = {ev.PRESENT: r'\cellcolor{stateopen}\color{white}applies',
         ev.UNCERTAIN: r'\cellcolor{stateunsure}uncertain',
         ev.ABSENT: r'\cellcolor{stateclosed}not applicable'}
LEVEL = {0: 'silent', 1: 'component', 2: 'capability', 3: 'harm'}


def synth_row(*cells):
    """A table row of invented data. \\rowcolor cannot follow \\input, so each cell is filled."""
    return ' & '.join(r'\cellcolor{synthfill}' + c for c in cells) + r' \\'


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEAD + text, encoding='utf-8')


def reference_tables(model, out):
    rows = []
    for code, c in model['components'].items():
        rows.append(node(model, code) + ' & ' + tex(c['label']) + ' & ' + c['origin'] + ' & '
                    + tex(c['feature']) + r' \\')
    write(out / 'reference-components.tex', '\n'.join(rows) + '\n\\bottomrule\n')
    rows = []
    for code, c in model['capabilities'].items():
        rows.append(code + ' & ' + tex(c['label']) + ' & ' + tex(c['actor']) + ' & \\texttt{'
                    + c['type'] + '} & ' + expression(model, c['needs']) + r' \\')
    write(out / 'reference-capabilities.tex', '\n'.join(rows) + '\n\\bottomrule\n')
    rows = []
    for code, harm in model['harms'].items():
        for i, p in enumerate(harm['pathways']):
            first = (r'\texttt{' + code + '}') if i == 0 else ''
            tag = r' (\texttt{T-REL})' if p.get('tag') else ''
            cites = ''.join(cite(s) for s in p['sources'])
            rows.append(first + ' & ' + p['id'] + ' & ' + p['capability'] + ' & '
                        + tex(p['consequence']) + tag + ' & ' + p['basis'] + ' & ' + cites + r' \\')
        rows.append(r'\addlinespace[2pt]')
    write(out / 'reference-pathways.tex', '\n'.join(rows[:-1]) + '\n\\bottomrule\n')


def test_tables(root, model, out_tables, out_figures, summary):
    study = root / '04_Study/4.7_Validation/Instrument-Test'
    llm = root / '05_Data/raw/policy-test_2026-11-01/llm'
    record = ev.load(study / 'applicability_clue.yaml')
    review = ev.load(study / 'review_clue.yaml')
    standin = ev.load(study / 'standin_coding_clue.yaml')
    walkthrough = ev.load(study / 'walkthrough_SYNTHETIC.yaml')
    units = load_units(llm)
    state_policy = {k: v['state'] for k, v in record['components'].items()}
    state_with = {k: v.get('with_walkthrough', v['state']) for k, v in record['components'].items()}
    paths_policy = ev.pathway_states(model, state_policy)
    paths_with = ev.pathway_states(model, state_with)
    seen = mentions(llm, standin, review)
    surface = {'policy': {}, 'interface': {}}
    for (unit, code), statuses in seen.items():
        side = 'policy' if unit.startswith('U') else 'interface'
        surface[side].setdefault(code, set()).update(statuses)

    # Coverage table
    rows = []
    levels = {'policy': Counter(), 'interface': Counter()}
    by_state = {'policy': Counter()}
    for code, harm in model['harms'].items():
        for i, p in enumerate(harm['pathways']):
            cells = []
            state = paths_policy[p['id']]
            for side, states in (('policy', paths_policy), ('interface', paths_with)):
                if states[p['id']] == ev.ABSENT:
                    cells.append(r'\cellcolor{stateclosed}--')
                    continue
                level, denied = coverage(model, surface[side], code, p)
                if states[p['id']] == ev.PRESENT:
                    levels[side][level] += 1
                if side == 'policy':
                    by_state['policy'][(state, level)] += 1
                cells.append(SHADE[level] + LEVEL[level] + (r'$^{\mathrm{d}}$' if denied else ''))
            first = (r'\texttt{' + code + '}') if i == 0 else ''
            rows.append(first + ' & ' + p['id'] + ' & ' + p['capability'] + ' & ' + tex(p['consequence'])
                        + ' & ' + STATE[state] + ' & ' + cells[0] + ' & ' + cells[1] + r' \\')
    write(out_tables / 'test-coverage.tex', '\n'.join(rows) + '\n\\bottomrule\n')

    # Applicability record
    rows = []
    for code, c in model['components'].items():
        rec = record['components'][code]
        evidence = ', '.join(rec['evidence']) or '--'
        after = rec.get('with_walkthrough')
        state = rec['state'] + ((r' $\to$ ' + after + r'\,\synthtag') if after else '')
        rows.append(node(model, code) + ' & ' + state + ' & ' + evidence + ' & ' + tex(rec['reason']) + r' \\')
    write(out_tables / 'test-applicability.tex', '\n'.join(rows) + '\n\\bottomrule\n')

    # Protection claims, with the check of necessary conditions
    rows = []
    claim_out = []
    decision = {'mismatch': r'\cellcolor{stateunsure}potential mismatch', 'none': 'no mismatch', 'unclear': 'not assessable'}
    for claim in review['claims']:
        after = ev.after_measure(model, state_policy, claim['removes'])
        still_open = [p for p in claim['in_scope'] if after[p] != ev.ABSENT]
        claim_out.append({'id': claim['id'], 'open': still_open, 'decision': claim['decision']})
        frame = claim['strength'] or '--'
        cut = (', '.join(still_open) or 'none') if claim['in_scope'] else '--'
        removes = ', '.join(node(model, c) for c in claim['removes']) or '--'
        rows.append(claim['id'] + ' & ' + ', '.join(claim['units']) + r' & \texttt{' + claim['code'] + '}; ' + frame
                    + ' & ' + tex(claim['claim']) + ' & ' + removes + ' & ' + cut + ' & ' + decision[claim['decision']]
                    + ' & ' + tex(claim['reason']) + r' \\')
    write(out_tables / 'test-claims.tex', '\n'.join(rows) + '\n\\bottomrule\n')
    short = []
    for claim, found in zip(review['claims'], claim_out):
        cut = (', '.join(found['open']) or 'none') if claim['in_scope'] else '--'
        short.append(claim['id'] + ' & ' + tex(claim['claim']) + r' & \texttt{' + claim['code'] + '}; '
                     + (claim['strength'] or '--') + ' & ' + cut + ' & ' + decision[claim['decision']] + r' \\')
    write(out_tables / 'test-claims-short.tex', '\n'.join(short) + '\n\\bottomrule\n')

    # Walkthrough (synthetic)
    rows = []
    q = {True: 'y', False: 'n'}
    for code, task in walkthrough['tasks'].items():
        answers = ' '.join(q[task['questions'][f'Q{i}']] for i in range(1, 5))
        rows.append(synth_row(code, tex(task['goal']), answers, str(task['taps']), task['outcome'],
                              tex(task['stopped_at'] or '--')))
    write(out_tables / 'test-walkthrough.tex', '\n'.join(rows) + '\n\\bottomrule\n')
    rows = []
    for u in walkthrough['interface_units']:
        labels = sorted(c for (unit, c) in seen if unit == u['unit'])
        rows.append(synth_row(u['unit'], tex(u['screen']), tex(u['text']),
                              ', '.join(node(model, c) if c in model['components'] else tex(c) for c in labels)))
    write(out_tables / 'test-interface.tex', '\n'.join(rows) + '\n\\bottomrule\n')

    # Unit-level labels of the policy
    rows = []
    groups = {}
    for (unit, code), statuses in seen.items():
        if unit.startswith('U'):
            groups.setdefault(unit, []).append((code, statuses))
    for unit in sorted(groups):
        items = []
        for code, statuses in sorted(groups[unit]):
            name = node(model, code) if code in model['components'] else tex(code)
            items.append(name + (r'$^{\mathrm{d}}$' if statuses == {'d'} else ''))
        rows.append(unit + ' & ' + tex(units[unit]['heading']) + ' & ' + ', '.join(items) + r' \\')
    write(out_tables / 'test-units.tex', '\n'.join(rows) + '\n\\bottomrule\n')

    # Model behaviour
    cmp = compare.main(str(llm), str(study / 'standin_coding_clue.yaml'))
    s1, s3 = cmp['stage1'], cmp['stage3']
    def row(name, s, para=''):
        v = s['votes']
        sm = s['vs_standin_majority']
        jac = s['jaccard_runs']
        low, high = min(jac.values()), max(jac.values())
        runs = sorted(s['per_run'].values())
        return (name + f" & {runs[0]}--{runs[-1]} & {s['union']} & {v['3']} & {v['2']} & {v['1']} & "
                + f"{low:.2f}--{high:.2f} & {sm['share_of_model_in_standin']:.2f} & {sm['share_of_standin_in_model']:.2f}" + r' \\')
    write(out_tables / 'test-llm.tex',
          row('Stage 1: nodes, harms', s1) + '\n' + row('Stage 3: measures', s3) + '\n\\bottomrule\n')
    # Votes chart
    fig = r'''\begin{tikzpicture}
\begin{axis}[
  xbar stacked, width=0.82\textwidth, height=3.4cm, bar width=4.5mm, xmin=0,
  ytick={0,1}, yticklabels={Stage 3: measures, Stage 1: nodes and harms},
  y=7.5mm, enlarge y limits=0.5, axis lines*=left, tick label style={font=\footnotesize},
  xlabel={Distinct labels (unit and code)}, xlabel style={font=\footnotesize},
  legend style={at={(0.5,1.05)},anchor=south,legend columns=3,font=\footnotesize,draw=none},
  legend cell align=left, nodes near coords, every node near coord/.append style={font=\scriptsize},
  reverse legend=false]
\addplot+[draw=primary,fill=primary,every node near coord/.append style={text=white}] coordinates {(%d,0) (%d,1)};
\addplot+[draw=primary,fill=primary!45,every node near coord/.append style={text=black}] coordinates {(%d,0) (%d,1)};
\addplot+[draw=primary,fill=primary!12,every node near coord/.append style={text=black}] coordinates {(%d,0) (%d,1)};
\legend{all three runs, two runs, one run}
\end{axis}
\end{tikzpicture}
''' % (s3['votes']['3'], s1['votes']['3'], s3['votes']['2'], s1['votes']['2'], s3['votes']['1'], s1['votes']['1'])
    write(out_figures / 'test-llm.tex', fig)

    # Stage 2 and 3 details per run
    stage3 = {}
    for r in compare.RUNS:
        data = json.load(open(llm / 'stage3' / f'run{r}.json', encoding='utf-8'))
        c = Counter(); strength = Counter(); framing = Counter()
        for entry in data['claims']:
            for cl in entry['claims']:
                c[cl['code']] += 1
                if cl.get('strength'):
                    strength[cl['strength']] += 1
                if cl.get('framing'):
                    framing[cl['framing']] += 1
        stage3[r] = {'codes': dict(c), 'strength': dict(strength), 'framing': dict(framing)}
    stage2 = {}
    for r in compare.RUNS:
        data = json.load(open(llm / 'stage2' / f'run{r}.json', encoding='utf-8'))
        stage2[r] = [(h['unit'], h['harm'], [s['code'] for s in h['stances']]) for h in data['harms']]

    # Discrimination tree with the states of the test app
    fill = {ev.PRESENT: 'stateopen', ev.UNCERTAIN: 'stateunsure', ev.ABSENT: 'stateclosed'}
    text = {ev.PRESENT: 'white', ev.UNCERTAIN: 'black', ev.ABSENT: 'black'}
    caps = ev.capability_states(model, state_policy)
    def leaf(name, code, x):
        c = model['components'][code]
        colour = {'core': 'origincore', 'context': 'originctx', 'implementation': 'originimp', 'external': 'originext'}[c['origin']]
        dash = ',dashed' if c['origin'] == 'external' else ''
        st = state_policy[code]
        mark = {ev.PRESENT: r'\checkmark', ev.UNCERTAIN: '?', ev.ABSENT: r'$\times$'}[st]
        return (rf'\node[leaf,draw={colour}{dash}] ({name}) at ({x},0) {{\textbf{{\textcolor{{{colour}}}{{{code}}}}} {mark}\\'
                + tex(c['label']) + '};\n')
    def cap_node(name, code, x):
        st = caps[code]
        return (rf'\node[capab,fill={fill[st]},text={text[st]}] ({name}) at ({x},2.75) {{\textbf{{{code}}} '
                + tex(model['capabilities'][code]['label']) + '};\n')
    harm_state = ev.harm_states(model, state_policy)['H-DSC']
    body = r'''\begin{tikzpicture}[
  font=\scriptsize,
  harm/.style={rounded corners=2pt,align=center,text width=70mm,minimum height=8mm,inner sep=3pt},
  capab/.style={draw=muted,rounded corners=2pt,align=center,text width=32mm,minimum height=9mm,inner sep=2pt},
  leaf/.style={line width=1pt,fill=white,rounded corners=2pt,align=center,text width=15.5mm,minimum height=15mm,inner sep=1.5pt},
  op/.style={font=\scriptsize\bfseries,fill=white,inner sep=1.2pt},
  edge/.style={semithick,draw=muted}]
'''
    body += (rf'\node[harm,fill={fill[harm_state]},text={text[harm_state]}] (h) at (0.6,4.9) '
             + r'{\textbf{Harm:} discrimination (\texttt{H-DSC})};' + '\n')
    positions = [('a', 'CO1', -7.6), ('b', 'CO2', -5.8), ('c', 'IM5', -4.0), ('d', 'IM6', -2.2), ('e', 'IM7', -0.4),
                 ('f', 'EX3', 1.6), ('g', 'IM9', 3.4), ('i', 'IM4', 5.4), ('j', 'CO2', 7.2)]
    names = {}
    for name, code, x in positions:
        body += leaf(name, code, x)
    body += cap_node('k2', 'K2', -4.0) + cap_node('k8', 'K8', 1.6) + cap_node('k10', 'K10', 6.3)
    for a in 'abcde':
        body += rf'\draw[edge] ({a}.north) -- (k2.south);' + '\n'
    for a in 'fg':
        body += rf'\draw[edge] ({a}.north) -- (k8.south);' + '\n'
    body += r'\draw[edge] (e.north) -- (k8.south);' + '\n'
    body += r'\draw[edge] (d.north) -- (k8.south);' + '\n'
    for a in 'ij':
        body += rf'\draw[edge] ({a}.north) -- (k10.south);' + '\n'
    body += r'\draw[edge] (e.north) -- (k10.south);' + '\n'
    for a in ('k2', 'k8', 'k10'):
        body += rf'\draw[edge] ({a}.north) -- (h.south);' + '\n'
    body += r'\node[op] at (-4.0,1.95) {(CO1 OR CO2) AND (IM5 OR IM6 OR IM7)};' + '\n'
    body += r'\node[op] at (1.6,1.95) {EX3 AND (IM6 OR IM7 OR IM9)};' + '\n'
    body += r'\node[op] at (6.3,1.95) {IM4 OR+ IM7 OR+ CO2};' + '\n'
    body += r'\node[op] at (0.6,3.95) {OR};' + '\n'
    body += r'\end{tikzpicture}' + '\n'
    write(out_figures / 'test-tree-dsc.tex', body)

    summary.update({
        'pathways_policy': dict(Counter(paths_policy.values())),
        'pathways_with_walkthrough': dict(Counter(paths_with.values())),
        'capabilities_policy': ev.capability_states(model, state_policy),
        'capabilities_with_walkthrough': ev.capability_states(model, state_with),
        'harms_policy': ev.harm_states(model, state_policy),
        'levels_applicable': {k: dict(v) for k, v in levels.items()},
        'by_state_policy': {f'{a}/{b}': n for (a, b), n in by_state['policy'].items()},
        'claims': claim_out,
        'stage2': stage2,
        'stage3': stage3,
        'stage1': s1,
        'stage3_compare': s3,
        'units_total': len([u for u in units if u.startswith('U')]),
        'units_with_labels': len(groups),
        'components': Counter(c['origin'] for c in model['components'].values()),
        'capabilities': len(model['capabilities']),
        'pathways': sum(len(h['pathways']) for h in model['harms'].values()),
        'basis': dict(Counter(p['basis'] for h in model['harms'].values() for p in h['pathways'])),
    })


def main(root):
    root = Path(root)
    model = ev.load(root / '04_Study/4.3_Analytical-Framework/reference_model_v1.yaml')
    ev.check_model(model)
    tables = root / '03_Thesis/tables'
    figures = root / '03_Thesis/figures'
    reference_tables(model, tables)
    summary = {}
    test_tables(root, model, tables, figures, summary)
    out = Path(__file__).parent / 'output' / 'summary.json'
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps(summary, indent=1, default=str), encoding='utf-8')
    print(json.dumps(summary, indent=0, default=str))


if __name__ == '__main__':
    main(sys.argv[1])
