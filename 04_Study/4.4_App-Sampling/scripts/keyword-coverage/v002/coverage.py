"""Health categories of the app sample (Results 5.2): main function and keyword groups.

Changes from v001: the ten keyword categories are grouped into the six health categories of the
domain (Methodology 4.4.1), and both views of the sample are written as one thesis table:

* main function: the primary category of each of the 50 apps (each app counts once);
* keyword groups: the ranked (not preinstalled) apps found within the first 30 positions of at
  least one query of the group, in either store (an app can be found by several groups).

It also counts how many groups found each ranked app. Reads the frozen collections and the sample;
writes output/categories.csv and 03_Thesis/tables/sample-categories.tex.

Usage: python coverage.py
"""
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
DATA = ROOT / "05_Data" / "App Sampling" / "26. Oct"
KEYWORDS = ROOT / "04_Study" / "4.4_App-Sampling" / "keywords.csv"
TABLE = ROOT / "03_Thesis" / "tables" / "sample-categories.tex"
DEPTH = 30

# keyword category (keywords.csv) -> health category of the domain
GROUP = {"cycling": "activity", "exercise": "activity", "running": "activity", "step count": "activity",
         "diet": "diet-weight", "weight": "diet-weight", "heart": "heart", "sleep": "sleep",
         "mood": "mood", "reproductive": "reproductive"}
# primary category (apps.csv) -> health category; "multiple" has no keyword group
PRIMARY = {"activity": "activity", "diet-weight": "diet-weight", "heart": "heart", "sleep": "sleep",
           "mood": "mood", "cycle": "reproductive", "pregnancy": "reproductive", "multiple": "multiple"}
ROWS = [("activity", "Activity"), ("diet-weight", "Diet and weight"), ("reproductive", "Reproductive health"),
        ("sleep", "Sleep"), ("mood", "Mood"), ("heart", "Heart rate"), ("multiple", "Multipurpose tracking")]


def hits_by_query(appstore, googleplay, depth=DEPTH):
    """Map query -> set of ('apple', id) / ('play', id) within the first `depth` positions."""
    hits = defaultdict(set)
    for query, rows in appstore["results"].items():
        for row in rows[:depth]:
            hits[query].add(("apple", str(row["ID"])))
    for query, rows in googleplay["search"].items():
        for row in rows:
            if int(row["Search Position"]) <= depth:
                hits[query].add(("play", str(row["ID"])))
    return hits


def groups_found(app, keywords, hits):
    """The health categories whose queries found the app."""
    ids = {("apple", app["apple_id"])} if app["apple_id"] else set()
    ids |= {("play", app["play_id"])} if app["play_id"] else set()
    return {GROUP[cat] for query, cat in keywords.items() if ids & hits.get(query, set())}


def pct(k, n):
    return f"{round(100 * k / n)}\\,\\%"


def main():
    with open(KEYWORDS, encoding="utf-8") as f:
        keywords = {row["query"]: row["category"] for row in csv.DictReader(f)}
    with open(DATA / "Processed" / "apps.csv", encoding="utf-8") as f:
        sample = list(csv.DictReader(f))
    with open(DATA / "Raw" / "appstore_2026-10-23.json", encoding="utf-8") as f:
        appstore = json.load(f)
    with open(DATA / "Raw" / "googleplay_2026-10-24.json", encoding="utf-8") as f:
        googleplay = json.load(f)
    hits = hits_by_query(appstore, googleplay)
    ranked = [a for a in sample if a["preinstalled"] == "False"]
    found = {a["order"]: groups_found(a, keywords, hits) for a in ranked}
    main_cat = Counter(PRIMARY[a["category"]] for a in sample)
    by_group = Counter(g for gs in found.values() for g in gs)
    n_all, n_ranked = len(sample), len(ranked)

    out = Path(__file__).parent / "output"
    out.mkdir(exist_ok=True)
    with open(out / "categories.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["order", "name", "primary_category", "groups_found"])
        for a in ranked:
            w.writerow([a["order"], a["name"], a["category"], " ".join(sorted(found[a["order"]]))])

    lines = ["% Generated by 04_Study/4.4_App-Sampling/scripts/keyword-coverage/v002/coverage.py "
             "from the frozen collections and the sample; do not edit by hand."]
    for key, label in ROWS:
        g = (f"{by_group[key]} & {pct(by_group[key], n_ranked)}" if key != "multiple" else "-- & --")
        lines.append(f"{label} & {main_cat[key]} & {pct(main_cat[key], n_all)} & {g} \\\\")
    lines.append("\\midrule")
    lines.append(f"\\textbf{{Apps}} & \\textbf{{{n_all}}} & \\textbf{{100\\,\\%}} & \\textbf{{{n_ranked}}} & -- \\\\")
    lines.append("\\bottomrule")  # a rule right after \input in the table is misplaced
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8")

    sizes = Counter(len(gs) for gs in found.values())
    print("main function:", dict(main_cat), "primary categories:", dict(Counter(a["category"] for a in sample)))
    print("found by group:", dict(by_group), "of", n_ranked)
    print("groups per ranked app:", dict(sorted(sizes.items())))
    own = sum(1 for a in ranked if PRIMARY[a["category"]] in found[a["order"]])
    print("ranked apps found by the group of their main function:", own)
    for key, _ in ROWS[:6]:
        other = sorted(a["name"][:30] for a in ranked if key in found[a["order"]] and PRIMARY[a["category"]] != key)
        print(f"  found by {key} but main function elsewhere: {len(other)} {other[:8]}")


if __name__ == "__main__":
    main()
