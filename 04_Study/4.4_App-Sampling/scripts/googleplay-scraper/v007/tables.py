"""Write the LaTeX tables of the Android sample for 03_Thesis-v2/tables/.

Reads the frozen collection of 21 November 2026 and the screening file;
prints the counts that the Results chapter states.
Usage (from the repository root): python <this file>
"""
import csv, json
from collections import Counter
from pathlib import Path

DATA = Path("05_Data/App Sampling/21. Nov")
STUDY = Path("04_Study/4.4_App-Sampling")
OUT = Path("03_Thesis-v2/tables")
HEAD = "% Generated by 04_Study/4.4_App-Sampling/scripts/googleplay-scraper/v007/tables.py; do not edit by hand.\n"
CATEGORY = {"activity": "Activity", "diet-weight": "Diet and weight", "cycle": "Reproductive health",
            "pregnancy": "Reproductive health", "sleep": "Sleep", "mood": "Mood",
            "heart": "Heart rate", "multiple": "Multipurpose"}
GROUP = {"cycling": "Cycling", "diet": "Diet", "exercise": "Exercise", "heart": "Heart rate",
         "mood": "Mood", "running": "Running", "sleep": "Sleep", "step count": "Step count",
         "weight": "Weight", "reproductive": "Reproductive health", "devices": "Devices and scales"}


def tex(text):
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\~{}"),
                 ("–", "--"), ("—", "---")]:
        text = text.replace(a, b)
    return text


def short(text, n):
    return text if len(text) <= n else text[: n - 1].rstrip(" -:,&") + "…"


def main():
    config = json.loads((DATA / "Raw/config.json").read_text(encoding="utf-8"))
    search = json.loads((DATA / "Raw/search.json").read_text(encoding="utf-8"))
    with open(DATA / "Raw/pages.jsonl", encoding="utf-8") as source:  # not splitlines(): U+2028 occurs
        pages = [json.loads(line) for line in source]
    cands = list(csv.DictReader(open(DATA / "Processed/candidates.csv", encoding="utf-8")))
    sample = list(csv.DictReader(open(DATA / "Processed/sample.csv", encoding="utf-8")))
    screen = {r["id"]: r for r in csv.DictReader(open(STUDY / "screening-android.csv", encoding="utf-8"))}

    # Keywords: the 49 queries of keywords.csv plus the queries added by the known-app check.
    groups = {}
    known = {r["query"]: r for r in csv.DictReader(open(STUDY / "keywords.csv", encoding="utf-8"))}
    added = {"fitness tracker": "en", "Fitnesstracker": "de", "smartband": "en+de", "scale": "en", "Waage": "de"}
    for query in config["keywords"]:
        row = known.get(query) or {"category": "devices", "language": added[query]}
        g = groups.setdefault(row["category"], {"en": [], "de": []})
        if row["language"] == "en+de":
            g["en"].append(query + "*")
        else:
            g[row["language"]].append(query)
    lines = [HEAD]
    for key, g in groups.items():
        source = {"reproductive": "Malki et al.", "devices": "Known-app check"}.get(key, "Hutton et al.")
        lines.append(f"{GROUP[key]} & {tex(', '.join(g['en']))} & {tex(', '.join(g['de']))} & {source} \\\\\n")
    lines.append("\\bottomrule\n")
    (OUT / "keywords.tex").write_text("".join(lines), encoding="utf-8")

    # The sample, one row per app.
    lines = [HEAD]
    for n, a in enumerate(sample, 1):
        category = CATEGORY[screen[a["appId"]]["category"]]
        reviews = f"{int(a['reviews']):,}".replace(",", "{,}")
        rank = a["rank"] if a["rank"] != "preinstalled" else "--"
        lines.append(f"{n} & {tex(short(a['title'], 34))} & {tex(short(a['developer'], 26))} & "
                     f"{category} & {reviews} & {rank} \\\\\n")
    lines.append("\\bottomrule\n")
    (OUT / "sample.tex").write_text("".join(lines), encoding="utf-8")

    # Screening in rank order up to the last selected app.
    last = max(int(a["rank"]) for a in sample if a["rank"] != "preinstalled")
    reached = [c for c in cands if int(c["rank"]) <= last and c["appId"] not in config["preinstalled"]]
    excluded = Counter(screen[c["appId"]]["rule"] for c in reached if screen[c["appId"]]["decision"] == "excluded")
    ranked = [a for a in sample if a["rank"] != "preinstalled"]

    cats = Counter(CATEGORY[screen[a["appId"]]["category"]] for a in sample)
    devs = Counter(a["developer"] for a in sample)
    best = {}
    for q, ids in search.items():
        for pos, i in enumerate(ids, 1):
            best[i] = min(best.get(i, 99), pos)
    print(json.dumps({
        "queries": len(search), "hits": sum(map(len, search.values())),
        "queries_under_30": sum(len(v) < 30 for v in search.values()),
        "min_hits": min(map(len, search.values())),
        "distinct_apps": len({i for v in search.values() for i in v}),
        "pages_ok": sum("error" not in p for p in pages), "pages_failed": sum("error" in p for p in pages),
        "candidates": len(cands), "reached": len(reached), "excluded": excluded,
        "eligible_reached": sum(screen[c["appId"]]["decision"] == "eligible" for c in reached),
        "last_rank": last, "reviews_range": [min(int(a["reviews"]) for a in ranked), max(int(a["reviews"]) for a in ranked)],
        "categories": cats, "developers_with_several": {d: n for d, n in devs.items() if n > 1},
        "best_position_top10": sum(best[a["appId"]] <= 10 for a in ranked),
        "free": Counter(a["free"] for a in sample),
    }, indent=1, ensure_ascii=False))


if __name__ == "__main__":
    main()
