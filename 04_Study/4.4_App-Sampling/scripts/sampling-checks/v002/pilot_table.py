"""Write the Google Play pilot's top apps as a thesis table (evidence for the developer rule, D2).

    python 04_Study/4.4_App-Sampling/scripts/sampling-checks/v002/pilot_table.py 05_Data/raw/app-sample_2026-10-25/googleplay-pilot_2026-10-22.json 03_Thesis/tables/developer-pilot.tex

The pool is that of v001/check_pool.py (at least 1,000 ratings, Samsung Health removed),
ranked by the worldwide rating count as in the pilot. Rows of a developer with several of
the top apps are shaded; the policy column drops the query string, which only names the app.
Standard library only.
"""
import argparse
import collections
import importlib.util
import json
from pathlib import Path

spec = importlib.util.spec_from_file_location('check_pool', Path(__file__).resolve().parents[1] / 'v001' / 'check_pool.py')
check_pool = importlib.util.module_from_spec(spec)
spec.loader.exec_module(check_pool)


def tex(text):
    s = ''.join(ch for ch in str(text or '') if ord(ch) < 256).replace('\\', '/')
    for a, b in (('&', r'\&'), ('%', r'\%'), ('#', r'\#'), ('_', r'\_'), ('$', r'\$'), ('{', r'\{'), ('}', r'\}')):
        s = s.replace(a, b)
    return s.replace('~', r'\textasciitilde{}').strip()


def num(n):
    return f'{int(n):,}'.replace(',', '{,}') if n not in (None, '') else '--'


def policy(url):
    return url.split('?')[0].split('://')[-1].removeprefix('www.').rstrip('/') if url else ''


def rows(data, top, floor=1000):
    ranked = check_pool.pool(data['results'], floor)[:top]
    several = collections.Counter(a['Dev. Name'] for a in ranked)
    return [(i, a, several[a['Dev. Name']] > 1) for i, a in enumerate(ranked, 1)]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('input')
    ap.add_argument('table')
    ap.add_argument('--top', type=int, default=47)
    args = ap.parse_args(argv)
    data = json.loads(Path(args.input).read_text(encoding='utf-8'))
    lines = [f"% Generated by 04_Study/4.4_App-Sampling/scripts/sampling-checks/v002/pilot_table.py from the pilot of {data['timestamp'][:10]}; "
             'do not edit by hand.']
    for i, a, shade in rows(data, args.top):
        lines.append(('\\rowcolor{devshade}' if shade else '') +
                     f"{i} & {tex(a['App Name'])} & {tex(a['Dev. Name'])} & \\path{{{policy(a.get('Privacy Policy URL'))}}} & "
                     f"{num(a['Rating Count'])} & {num(a.get('Review Count'))} \\\\")
    Path(args.table).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    counts = collections.Counter(a['Dev. Name'] for _, a, shade in rows(data, args.top) if shade)
    print(data['timestamp'], dict(counts))


if __name__ == '__main__':
    main()
