"""Build the harm trees use case by use case and write the tables and figures of Chapter 5.

    python build_usecases.py <repo_root>

Reads 04_Study/4.3_Analytical-Framework/use_cases_v1.yaml (the cards) and reference_model_v2.yaml
(definitions of components, capabilities and pathways). For each use case, in order, it adds
the components of the card to those already known, evaluates which capabilities and pathways
become possible, and records what is new. The final state must equal the reference model
(procedure of D23). Writes 03_Thesis/tables/usecase-*.tex.
"""
import re
import sys
from itertools import product
from pathlib import Path

import yaml

HEAD = '% Generated by scripts/harm-tree-usecases/v001/build_usecases.py; do not edit.\n'
ORIGIN = {'core': r'\ocore', 'context': r'\octx', 'implementation': r'\oimp', 'external': r'\oext'}
ORIGIN_COLOUR = {'core': 'origincore', 'context': 'originctx', 'implementation': 'originimp',
                 'external': 'originext'}
STOP_RUN = 2  # consecutive check cases without a new component that end the construction


# ---------------------------------------------------------------- formulas

def leaves(expr):
    if isinstance(expr, str):
        return [expr]
    (_, children), = expr.items()
    return [x for c in children for x in leaves(c)]


def holds(expr, avail):
    if isinstance(expr, str):
        return expr in avail
    (op, children), = expr.items()
    values = [holds(c, avail) for c in children]
    return all(values) if op == 'and' else any(values)


def terms(expr, avail):
    """Minimal sufficient sets of available components (the DNF of the formula)."""
    if isinstance(expr, str):
        return {frozenset([expr])} if expr in avail else set()
    (op, children), = expr.items()
    parts = [terms(c, avail) for c in children]
    if op == 'or':
        out = set().union(*parts) if parts else set()
    else:
        out = {frozenset()}
        for part in parts:
            out = {a | b for a, b in product(out, part)}
    return {t for t in out if not any(o < t for o in out)}


def prune(expr, avail):
    """The formula as built so far: unavailable components removed, single children lifted."""
    if isinstance(expr, str):
        return expr if expr in avail else None
    (op, children), = expr.items()
    kids = [prune(c, avail) for c in children]
    if op == 'and':
        if any(k is None for k in kids):
            return None
    else:
        kids = [k for k in kids if k is not None]
        if not kids:
            return None
    return kids[0] if len(kids) == 1 else {op: kids}


# ---------------------------------------------------------------- accretion

def accrete(model, cases):
    """One record per use case: what its card adds to the state before it."""
    avail, enabled, paths = set(), set(), set()
    seen_terms = {k: set() for k in model['capabilities']}
    pathways = {p['id']: (h, p) for h, hd in model['harms'].items() for p in hd['pathways']}
    steps = []
    for uc in cases:
        used = [c for slot in uc['card'] for c in slot['components']]
        new_c = [c for c in dict.fromkeys(used) if c not in avail]
        avail |= set(used)
        new_k = [k for k, cap in model['capabilities'].items()
                 if k not in enabled and holds(cap['needs'], avail)]
        enabled |= set(new_k)
        branches = []
        for k, cap in model['capabilities'].items():
            now = terms(cap['needs'], avail)
            added = now - seen_terms[k]
            if added and k not in new_k:
                branches.append((k, len(added)))
            seen_terms[k] = now
        new_p = [pid for pid, (_, p) in pathways.items()
                 if pid not in paths and p['capability'] in enabled]
        paths |= set(new_p)
        steps.append({'uc': uc, 'new_components': new_c, 'new_capabilities': new_k,
                      'widened': branches, 'new_pathways': new_p,
                      'avail': set(avail), 'enabled': set(enabled), 'paths': set(paths)})
    return steps


def check(model, cases, steps, bib_keys=None):
    errors = []
    codes = set(model['components'])
    ids = [uc['id'] for uc in cases]
    if len(ids) != len(set(ids)):
        errors.append('duplicate use case id')
    for uc in cases:
        for slot in uc['card']:
            for c in slot['components']:
                if c not in codes:
                    errors.append(f"{uc['id']}: unknown component {c}")
            if slot['components'] and not slot.get('evidence'):
                errors.append(f"{uc['id']}: slot {slot['q']} names components but no evidence")
            for e in slot.get('evidence', []):
                key = e.split(' ')[0]
                if bib_keys is not None and key not in bib_keys:
                    errors.append(f"{uc['id']}: citation key {key} not in references.bib")
                if not re.search(r' (p\. \d+|pp\. \d+--\d+|App\. [A-Z]|\S+ \d)', e):
                    errors.append(f"{uc['id']}: evidence {e!r} lacks a page or section")
    final = steps[-1]
    missing = codes - final['avail']
    if missing:
        errors.append('components never introduced: ' + ', '.join(sorted(missing)))
    for k in model['capabilities']:
        if k not in final['enabled']:
            errors.append(f'capability {k} never becomes possible')
    allp = {p['id'] for hd in model['harms'].values() for p in hd['pathways']}
    if allp != final['paths']:
        errors.append('pathways differ from the model: ' + ', '.join(sorted(allp ^ final['paths'])))
    roles = [uc['role'] for uc in cases]
    if 'check' in roles and 'build' in roles[roles.index('check'):]:
        errors.append('a build case follows a check case')
    for s in steps:
        if s['uc']['role'] == 'check' and (s['new_components'] or s['new_capabilities']
                                           or s['new_pathways'] or s['widened']):
            errors.append(f"{s['uc']['id']} is a check case but adds something")
    tail = steps[-STOP_RUN:]
    if len(tail) < STOP_RUN or any(s['uc']['role'] != 'check' for s in tail):
        errors.append(f'the last {STOP_RUN} use cases must be check cases')
    for a, b in zip(steps, steps[1:]):  # monotone: nothing is lost
        if not (a['avail'] <= b['avail'] and a['enabled'] <= b['enabled'] and a['paths'] <= b['paths']):
            errors.append(f"state shrinks from {a['uc']['id']} to {b['uc']['id']}")
    return errors


def bib_keys(root):
    text = (Path(root) / '03_Thesis/references.bib').read_text(encoding='utf-8')
    return set(re.findall(r'@\w+\{([^,\s]+),', text))


# ---------------------------------------------------------------- LaTeX

def tex(text):
    for a, b in (('\\', r'\textbackslash{}'), ('&', r'\&'), ('%', r'\%'), ('_', r'\_'), ('#', r'\#'),
                 ('$', r'\$')):
        text = text.replace(a, b)
    return text.replace(' -- ', ' -- ')


def node(model, code):
    if code in model['components']:
        return ORIGIN[model['components'][code]['origin']] + '{' + code + '}'
    return code


def expression(model, expr):
    if isinstance(expr, str):
        return node(model, expr)
    (op, children), = expr.items()
    word = {'and': ' AND ', 'or': ' OR '}[op]
    parts = [('(' + expression(model, c) + ')') if isinstance(c, dict) else expression(model, c)
             for c in children]
    return word.join(parts)


def cite(source):
    key, _, rest = source.partition(' ')
    return r'\parencite[' + rest.replace(' ', '~').replace('--', '--') + ']{' + key + '}'


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEAD + text, encoding='utf-8')


def ids(model, items):
    return ', '.join(node(model, c) for c in items) if items else '--'


def steps_table(model, steps):
    rows, last = [], None
    cc = kk = pp = 0
    for s in steps:
        uc = s['uc']
        if last and uc['role'] != last:
            rows.append(r'\midrule')
        last = uc['role']
        cc += len(s['new_components'])
        kk += len(s['new_capabilities'])
        pp += len(s['new_pathways'])
        widened = ', '.join(f'{k}\\,+{n}' for k, n in s['widened']) or '--'
        rows.append(' & '.join([
            f"{uc['id']} {tex(uc['title'])}",
            ids(model, s['new_components']),
            ', '.join(s['new_capabilities']) or '--',
            widened,
            ', '.join(s['new_pathways']) or '--',
            f'{cc}/{kk}/{pp}']) + r' \\')
    write_rows = '\n'.join(rows)
    return write_rows + '\n\\bottomrule\n'


def provider_free(model):
    """Pathways that need no implementation choice: some sufficient set holds none."""
    every = set(model['components'])
    free = set()
    for hd in model['harms'].values():
        for p in hd['pathways']:
            for t in terms(model['capabilities'][p['capability']]['needs'], every):
                if all(model['components'][c]['origin'] != 'implementation' for c in t):
                    free.add(p['id'])
    return free


def harms_table(model, steps):
    first = {p: s['uc']['id'] for s in steps for p in s['new_pathways']}
    free = provider_free(model)
    rows = []
    for h, hd in model['harms'].items():
        pw = hd['pathways']
        caps = list(dict.fromkeys(p['capability'] for p in pw))
        rows.append(' & '.join([
            r'\texttt{' + h + '} ' + tex(hd['label']),
            ', '.join(f"{p['id']} ({first[p['id']]})" for p in pw),
            ', '.join(caps),
            ', '.join(p['id'] for p in pw if p['id'] in free) or '--'
        ]) + r' \\')
    return '\n'.join(rows) + '\n\\bottomrule\n'


def common_subtrees(model):
    feeds = {}
    for h, hd in model['harms'].items():
        for p in hd['pathways']:
            feeds.setdefault(p['capability'], []).append(h)
    return {k: list(dict.fromkeys(v)) for k, v in feeds.items() if len(set(v)) >= 2}


def common_table(model, steps):
    first = {}
    for s in steps:
        for k in s['new_capabilities']:
            first[k] = s['uc']['id']
    rows = []
    for k, hs in common_subtrees(model).items():
        cap = model['capabilities'][k]
        rows.append(' & '.join([
            k + ' ' + tex(cap['label']), tex(cap['actor']),
            ', '.join(h.replace('H-', '') for h in hs), first[k],
            expression(model, cap['needs'])]) + r' \\')
    return '\n'.join(rows) + '\n\\bottomrule\n'


def cards_table(model, cases, steps):
    rows = []
    for s in steps:
        uc = s['uc']
        if rows:
            rows.append(r'\midrule')
        # an ordinary row: \multicolumn cannot open a row that follows \input
        rows.append(r'\textbf{' + uc['id'] + r'} & \textbf{' + tex(uc['title']) + r'} \emph{('
                    + uc['role'] + r')} & & & \\')
        for slot in uc['card']:
            cites = '; '.join(cite(e) for e in slot.get('evidence', []))
            rows.append(' & '.join([
                slot['q'], tex(slot['answer']), ids(model, slot['components']),
                slot.get('basis', ''), cites]) + r' \\')
        for o in uc.get('out_of_scope', []):
            rows.append(' & '.join(['excluded', tex(o['item'] + ': ' + o['reason']), '', '', '']) + r' \\')
    return '\n'.join(r for r in rows if r) + '\n\\bottomrule\n'


# ---------------------------------------------------------------- TikZ

SLOT, ROW = 2.35, 1.55  # cm between leaves, between rows
MAX_WIDTH = 15.2  # cm available for a figure


def layout_expr(expr, x0, depth, out, edges):
    """Place the formula tree; returns (node name, x). Leaves share one bottom row later."""
    if isinstance(expr, str):
        name = f'n{len(out)}'
        out.append({'name': name, 'kind': 'leaf', 'code': expr, 'x': x0 + SLOT / 2, 'depth': depth})
        return name, x0 + SLOT / 2, SLOT
    (op, children), = expr.items()
    name = f'n{len(out)}'
    out.append({'name': name, 'kind': 'gate', 'op': op.upper(), 'depth': depth})
    me = out[-1]
    x, xs = x0, []
    for c in children:
        cname, cx, cw = layout_expr(c, x, depth + 1, out, edges)
        edges.append((name, cname, None))
        xs.append(cx)
        x += cw
    me['x'] = sum(xs) / len(xs)
    return name, me['x'], x - x0


def tikz_for_step(model, step):
    new_paths = step['new_pathways']
    if not new_paths:
        return None
    pw = {p['id']: (h, p) for h, hd in model['harms'].items() for p in hd['pathways']}
    caps = list(dict.fromkeys(pw[p][1]['capability'] for p in new_paths))
    nodes, edges, cap_x, x = [], [], {}, 0.0
    for k in caps:
        tree = prune(model['capabilities'][k]['needs'], step['avail'])
        sub, sub_edges = [], []
        name, cx, width = layout_expr(tree, x, 2, sub, sub_edges)
        # rename to keep names unique across capabilities
        prefix = f'{k}_'
        ren = {n['name']: prefix + n['name'] for n in sub}
        for n in sub:
            n['name'] = ren[n['name']]
        nodes += sub
        edges += [(ren[a], ren[b], None) for a, b, _ in sub_edges]
        cap_x[k] = (cx, ren[name])
        x += width + 0.3
    total = x - 0.3
    max_depth = max(n['depth'] for n in nodes)
    harms = {}
    for p in new_paths:
        h, rec = pw[p]
        harms.setdefault(h, []).append((p, rec['capability']))
    hx = {h: sum(cap_x[k][0] for _, k in v) / len(v) for h, v in harms.items()}
    order = sorted(hx, key=hx.get)
    placed = {}
    gap = 2.5
    for h in order:
        px = hx[h]
        if placed:
            px = max(px, max(placed.values()) + gap)
        placed[h] = px
    shift = (sum(hx.values()) / len(hx)) - (sum(placed.values()) / len(placed))
    placed = {h: v + shift for h, v in placed.items()}
    left = min([0.0] + [v - 1.2 for v in placed.values()])
    right = max([total] + [v + 1.2 for v in placed.values()])
    width = right - left
    scale = min(1.0, MAX_WIDTH / width)
    lines = []
    lines.append(r'\begin{tikzpicture}[font=\scriptsize,x=1cm,y=1cm,'
                 r'hxharm/.style={draw=black!50,fill=black!6,rounded corners=2pt,align=center,'
                 r'text width=2.1cm,minimum height=8mm,inner sep=2pt},'
                 r'hxcap/.style={draw=accent,fill=accent!10,rounded corners=2pt,align=center,'
                 r'text width=2.3cm,minimum height=8mm,inner sep=2pt},'
                 r'hxgate/.style={draw=black!55,circle,inner sep=1.2pt,font=\tiny\bfseries,fill=white},'
                 r'hxleaf/.style={draw=#1,thick,rounded corners=1pt,align=center,fill=white,'
                 r'text width=2.05cm,minimum height=8mm,inner sep=2pt},'
                 r'hxed/.style={semithick,draw=black!55}]')
    for h, v in placed.items():
        label = tex(model['harms'][h]['label'])
        lines.append(f'  \\node[hxharm] ({h.replace("-", "")}) at ({v:.2f},0) {{\\textbf{{{label}}}}};')
    for k in caps:
        cx, rootname = cap_x[k]
        lines.append(f'  \\node[hxcap] ({k}) at ({cx:.2f},{-ROW:.2f}) '
                     f'{{\\textbf{{{k}}}\\\\{tex(model["capabilities"][k]["label"])}}};')
    for n in nodes:
        if n['kind'] == 'gate':
            y = -ROW * (n['depth'])
            lines.append(f'  \\node[hxgate] ({n["name"]}) at ({n["x"]:.2f},{y:.2f}) {{{n["op"]}}};')
        else:
            y = -ROW * (max_depth + 0.2)
            comp = model['components'][n['code']]
            colour = ORIGIN_COLOUR[comp['origin']]
            fresh = n['code'] in step['new_components']
            style = f'hxleaf={colour}' + (',fill=black!8' if fresh else '')
            label = tex(comp['label'])
            lines.append(f'  \\node[{style}] ({n["name"]}) at ({n["x"]:.2f},{y:.2f}) '
                         f'{{{ORIGIN[comp["origin"]]}{{{n["code"]}}}\\\\{label}}};')
    for k in caps:
        lines.append(f'  \\draw[hxed] ({k}.south) -- ({cap_x[k][1]}.north);')
    for a, b, _ in edges:
        lines.append(f'  \\draw[hxed] ({a}.south) -- ({b}.north);')
    for h, v in harms.items():
        for p, k in v:
            lines.append(f'  \\draw[hxed] ({h.replace("-", "")}.south) -- ({k}.north) '
                         f'node[midway,fill=white,inner sep=0.8pt,font=\\tiny]{{{p}}};')
    lines.append(r'\end{tikzpicture}')
    body = '\n'.join(lines)
    if scale < 1.0:
        body = f'\\scalebox{{{scale:.3f}}}{{%\n{body}}}'
    return body


def crossings(hpos, cpos, links):
    edges = [(hpos[h], cpos[k]) for h, k, _ in links]
    return sum(1 for i, (a, b) in enumerate(edges) for c, d in edges[i + 1:] if (a - c) * (b - d) < 0)


def least_crossing_order(harms, caps, links):
    """Order harms and capabilities so that few pathway lines cross (layout only).

    Every order of the harms is tried; for each, the capabilities are sorted by the mean position
    of their harms, then improved by swapping neighbours. Ties keep the first order found.
    """
    from itertools import permutations
    best = None
    for order in permutations(harms):
        hpos = {h: i for i, h in enumerate(order)}
        bary = {k: sum(hpos[h] for h, c, _ in links if c == k) / max(1, sum(1 for _, c, _ in links if c == k))
                for k in caps}
        cs = sorted(caps, key=lambda k: (bary[k], caps.index(k)))
        cpos = {k: i for i, k in enumerate(cs)}
        n = crossings(hpos, cpos, links)
        improved = True
        while improved:
            improved = False
            for i in range(len(cs) - 1):
                cs[i], cs[i + 1] = cs[i + 1], cs[i]
                cpos = {k: j for j, k in enumerate(cs)}
                m = crossings(hpos, cpos, links)
                if m < n:
                    n, improved = m, True
                else:
                    cs[i], cs[i + 1] = cs[i + 1], cs[i]
        if best is None or n < best[0]:
            best = (n, list(order), list(cs))
    return best[1], best[2]


def general_tikz(model):
    """Harms above, capabilities below, one line per pathway."""
    links = [(h, p['capability'], p['id']) for h, hd in model['harms'].items() for p in hd['pathways']]
    harm_order, caps = least_crossing_order(list(model['harms']), list(model['capabilities']), links)
    hpos = {h: i for i, h in enumerate(harm_order)}
    cpos = {k: i for i, k in enumerate(caps)}
    dx_c, dx_h = 1.25, 2.0
    width_c = (len(caps) - 1) * dx_c
    width_h = (len(harm_order) - 1) * dx_h
    off_h = (width_c - width_h) / 2
    lines = [r'\begin{tikzpicture}[font=\scriptsize,x=1cm,y=1cm,'
             r'hxharm/.style={draw=black!50,fill=black!6,rounded corners=2pt,align=center,'
             r'text width=1.7cm,minimum height=8mm,inner sep=2pt},'
             r'hxcap/.style={draw=accent,fill=accent!10,rounded corners=2pt,align=center,'
             r'minimum width=9mm,minimum height=7mm,inner sep=2pt},'
             r'hxsh/.style={draw=accent,fill=accent!30,rounded corners=2pt,align=center,'
             r'minimum width=9mm,minimum height=7mm,inner sep=2pt},'
             r'hxed/.style={thin,draw=black!45}]']
    for h in harm_order:
        name = h.replace('-', '')
        label = tex(model['harms'][h]['label'])
        x = off_h + hpos[h] * dx_h
        lines.append(r'  \node[hxharm] (' + name + ') at (' + f'{x:.2f}' + r',0) {\textbf{' + label + '}};')
    shared = set(common_subtrees(model))
    for k in caps:
        style = 'hxsh' if k in shared else 'hxcap'
        lines.append(r'  \node[' + style + '] (' + k + ') at (' + f'{cpos[k] * dx_c:.2f}' + r',-3.2) {\textbf{' + k + '}};')
        lines.append(r'  \node[font=\tiny,text width=1.15cm,align=center,anchor=north,inner sep=1pt] at ('
                     + k + r'.south) {' + tex(model['capabilities'][k]['label']) + '};')
    for h, k, _ in links:
        lines.append(r'  \draw[hxed] (' + h.replace('-', '') + '.south) -- (' + k + '.north);')
    lines.append(r'\end{tikzpicture}')
    return '\n'.join(lines)


# ---------------------------------------------------------------- main

def summary(model, steps):
    final = steps[-1]
    comps = {o: sum(1 for c in model['components'].values() if c['origin'] == o) for o in ORIGIN}
    return {'components': len(final['avail']), 'by_origin': comps,
            'capabilities': len(final['enabled']), 'pathways': len(final['paths']),
            'harms': len(model['harms']), 'common': list(common_subtrees(model)),
            'provider_free': sorted(provider_free(model)),
            'basis': basis_counts(steps)}


def basis_counts(steps):
    """Basis of the answer that introduced each component, and of the check-case answers."""
    intro, checks = {}, {'documented': 0, 'argued': 0}
    for s in steps:
        for slot in s['uc']['card']:
            if not slot['components']:
                continue
            if s['uc']['role'] == 'check':
                checks[slot['basis']] += 1
            for c in slot['components']:
                if c in s['new_components'] and c not in intro:
                    intro[c] = slot['basis']
    argued = sorted(c for c, b in intro.items() if b == 'argued')
    return {'components_documented': len(intro) - len(argued), 'components_argued': argued,
            'check_answers': checks}


def main(root):
    root = Path(root)
    model = yaml.safe_load((root / '04_Study/4.3_Analytical-Framework/reference_model_v2.yaml').read_text(encoding='utf-8'))
    data = yaml.safe_load((root / '04_Study/4.3_Analytical-Framework/use_cases_v1.yaml').read_text(encoding='utf-8'))
    cases = data['use_cases']
    steps = accrete(model, cases)
    errors = check(model, cases, steps, bib_keys(root))
    if errors:
        print('\n'.join('ERROR ' + e for e in errors))
        return 1
    out = root / '03_Thesis/tables'
    write(out / 'usecase-steps.tex', steps_table(model, steps))
    write(out / 'usecase-harms.tex', harms_table(model, steps))
    write(out / 'usecase-common.tex', common_table(model, steps))
    write(out / 'usecase-cards.tex', cards_table(model, cases, steps))
    write(out / 'usecase-general-tree.tex', general_tikz(model) + '\n')
    for s in steps:
        body = tikz_for_step(model, s)
        if body:
            write(out / f"usecase-tree-{s['uc']['id']}.tex", body + '\n')
    print(summary(model, steps))
    for s in steps:
        print(s['uc']['id'], s['uc']['role'], 'components', s['new_components'], 'capabilities',
              s['new_capabilities'], 'widened', s['widened'], 'pathways', s['new_pathways'])
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else '.'))
