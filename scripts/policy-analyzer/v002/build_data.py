"""Write the site's data file from the frozen instruments.

    python build_data.py [<repo root>]

Reads the reference model and the stage prompts of the instrument bundle of
5 November 2026 and writes output/data.js, which index.html loads. The site
never holds its own copy of the trees or prompts: rebuild after any change.
"""
import hashlib
import json
import pathlib
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
MODEL = '04_Study/Reference-Model/reference_model_v2.yaml'
PROMPTS = {
    'stage1': '04_Study/Prompts/stage1_coverage_v2.md',
    'stage1p': '04_Study/Prompts/stage1_coverage_v2p.md',
    'stage2': '04_Study/Prompts/stage2_stance_v2.md',
    'stage3': '04_Study/Prompts/stage3_protection_v2.md',
}


def body(text):
    """Strip the YAML header of a prompt file; the header documents, the body instructs."""
    if text.startswith('---'):
        end = text.index('\n---', 3)
        return text[end + 4:].lstrip('\n')
    return text


def header(text):
    if not text.startswith('---'):
        return {}
    end = text.index('\n---', 3)
    return yaml.safe_load(text[3:end]) or {}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main(root):
    root = pathlib.Path(root).resolve()
    model_path = root / MODEL
    model = yaml.safe_load(model_path.read_text(encoding='utf-8'))
    prompts, sources = {}, {'model': {'path': MODEL, 'sha256': sha(model_path)}}
    for key, rel in PROMPTS.items():
        path = root / rel
        text = path.read_text(encoding='utf-8')
        prompts[key] = body(text)
        sources[key] = {'path': rel, 'sha256': sha(path), 'version': header(text).get('version')}
    data = {'model': model, 'prompts': prompts, 'sources': sources}
    out = HERE / 'output'
    out.mkdir(exist_ok=True)
    js = ('// Generated by build_data.py from the frozen instruments; do not edit.\n'
          'window.PA_DATA = ' + json.dumps(data, ensure_ascii=False, indent=1, default=str) + ';\n')
    (out / 'data.js').write_text(js, encoding='utf-8')
    print(f"wrote {out / 'data.js'}: {len(model['components'])} components, "
          f"{len(model['capabilities'])} capabilities, "
          f"{sum(len(h['pathways']) for h in model['harms'].values())} pathways")


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else HERE.parents[2])
