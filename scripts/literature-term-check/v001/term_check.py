"""Compare the search terms with published term lists and with works held before the search (D21).

    python scripts/literature-term-check/v001/term_check.py

Run after the search of 28 October 2026 and without effect on it: this documents the overlap of
the terms with published vocabularies, not where they came from. Reads the frozen search and writes
03_Thesis/tables/literature-term-check.tex. Terms are matched with the search's own rules (lit.py).
"""
import csv
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
FROZEN = ROOT / "05_Data" / "Literature Search" / "28. Oct"
OUT = ROOT / "03_Thesis" / "tables" / "literature-term-check.tex"

# Term lists reported by works in the thesis bibliography, each read in the PDF (locators in D21).
LISTS = {
    "baumann2025llm": ["human annotation", "expert annotation", "crowdsourced annotation", "human coder*",
                       "human coding", "text classification", "text categorization", "manual annotation",
                       "gpt", "large language model", "llm*", "benchmark", "outperform", "social science",
                       "communication science", "sociology", "political science"],
    "hutton2018assessing": ["cycling", "diet", "eating", "exercise", "workouts", "heartrate", "heart rate", "mood",
                            "happiness", "walking", "running", "sleep", "steps", "weight", "body fat"],
    "malki2024exploring": ["female health", "women's health", "reproductive health", "fertility", "ovulation",
                           "menstrual", "menstruation", "period", "contraception", "birth control", "pregnancy",
                           "pregnant"],
    "niksirat2024wearable": ["physical activity data", "fitness data", "fitness tracking",
                             "wearable activity tracking", "physical activity tracker", "fitness tracker",
                             "wearable activity tracker", "utility", "privacy", "security", "perception",
                             "understanding", "experience", "expectation", "sharing", "system", "device",
                             "application", "app", "service", "bracelet", "wrist-worn"],
    "shipp2020period": ["period tracker", "period", "menstrual cycle", "menstruation tracker", "menstrual calendar"],
    "doan2024transparency": ["risk", "harm", "benefit", "compensation"],
}

# A spelling or inflection of another term of its group takes that term's result.
VARIANTS = {"m-health": "mhealth", "smart watch*": "smartwatch*", "reidentif*": "re-identif*",
            "de-anonymi*": "deanonymi*", "inferred": "infer", "inferring": "infer", "analyz*": "analys*",
            "framed": "framing", "llms": "llm"}

LISTED, WORD, HELD, NEITHER = "listed", "word", "held", "neither"


def load_lit():
    spec = importlib.util.spec_from_file_location("lit", ROOT / "scripts/literature-search/v002/lit.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def in_list(term, items, lit):
    """The term, with its truncation, is an entry or a phrase within one; or an entry's truncation covers it."""
    text = lit.norm_text(term.replace("*", ""))
    return any(lit.term_regex(term).search(lit.norm_text(i.replace("*", ""))) or
               (i.endswith("*") and lit.term_regex(i).match(text)) for i in items)


def word_plus_app(term, lists):
    """A published single word followed by app* or track*, as in "fertility app*"."""
    words = term.split()
    return len(words) == 2 and words[1] in ("app*", "track*") and any(words[0] in items for items in lists.values())


def classify(term, lit, texts, lists=LISTS):
    if any(in_list(term, items, lit) for items in lists.values()):
        return LISTED
    if word_plus_app(term, lists):
        return WORD
    return HELD if any(lit.term_regex(term).search(t) for t in texts) else NEITHER


def held_before(lit):
    """Titles and abstracts of the works that entered through the thesis citations or the Methods Digest."""
    csv.field_size_limit(10**8)
    with (FROZEN / "records.csv").open(encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f)
                if {"digest", "thesis"} & {x.strip() for x in r["routes"].replace(";", ",").split(",")}]
    return [lit.norm_text(r["title"] + " " + r["abstract"]) for r in rows], sum(not r["abstract"] for r in rows)


def results(cfg, lit, texts, lists=LISTS):
    return {gid: {t: classify(VARIANTS.get(t, t), lit, texts, lists) for t in group["terms"]}
            for gid, group in cfg["groups"].items()}


def tex(term):
    return term.replace("&", r"\&")


def table(cfg, res):
    lines = ["% Generated by scripts/literature-term-check/v001/term_check.py from the frozen search; do not edit."]
    for gid, terms in res.items():
        by = {k: [t for t, v in terms.items() if v == k] for k in (LISTED, WORD, HELD, NEITHER)}
        first = [tex(t) for t in by[LISTED]] + [tex(t) + r"$^{a}$" for t in by[WORD]]
        cells = [", ".join(first) or "--", ", ".join(map(tex, by[HELD])) or "--", ", ".join(map(tex, by[NEITHER])) or "--"]
        lines.append(f"{gid} & " + " & ".join(r"\footnotesize " + c for c in cells) + r" \\")
    lines.append(r"\bottomrule")
    return "\n".join(lines) + "\n"


def main():
    lit = load_lit()
    cfg = json.loads((ROOT / "scripts/literature-search/v003/config.json").read_text(encoding="utf-8"))
    texts, no_abstract = held_before(lit)
    res = results(cfg, lit, texts)
    OUT.write_text(table(cfg, res), encoding="utf-8", newline="\n")
    print(f"works held before the search: {len(texts)}, without abstract: {no_abstract}")
    kinds = (LISTED, WORD, HELD, NEITHER)
    print(f"{'':4}" + "".join(f"{k:>9}" for k in kinds) + f"{'all':>6}")
    for gid, terms in res.items():
        c = [sum(v == k for v in terms.values()) for k in kinds]
        print(f"{gid:4}" + "".join(f"{x:9}" for x in c) + f"{sum(c):6}")
    entries = [(t, v) for terms in res.values() for t, v in terms.items()]
    print(f"{'all':4}" + "".join(f"{sum(v == k for _, v in entries):9}" for k in kinds) + f"{len(entries):6}")
    unique = dict(entries)
    print(f"{'uniq':4}" + "".join(f"{sum(v == k for v in unique.values()):9}" for k in kinds) + f"{len(unique):6}")


if __name__ == "__main__":
    main()
