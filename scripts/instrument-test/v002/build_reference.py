"""Generate the reference-model tables from model v2 and re-evaluate the test app.

    python build_reference.py <repo_root>

Writes 03_Thesis/tables/reference-*.tex (Appendix G) from
04_Study/Reference-Model/reference_model_v2.yaml, and output/reevaluation_clue.{json,md}:
the capability and pathway states of the instrument-test app under model v1 with the
original fixture, and under model v2 with the re-evaluated record. The instrument-test
tables of Chapter 5 and Appendix H stay those of v001 (they describe the test of
1 November 2026 and need the raw data in 05_Data/raw/policy-test_2026-11-01/).
"""
import json
import sys
from pathlib import Path

import evaluate as ev

HEAD = r'% Generated by scripts/instrument-test/v002/build_reference.py; do not edit.' + '\n'
ORIGIN = {'core': r'\ocore', 'context': r'\octx', 'implementation': r'\oimp', 'external': r'\oext'}


def tex(text):
    for a, b in (('\\', r'\textbackslash{}'), ('&', r'\&'), ('%', r'\%'), ('_', r'\_'), ('#', r'\#'),
                 ('$', r'\$')):
        text = text.replace(a, b)
    return text


def node(model, code):
    if code in model['components']:
        return ORIGIN[model['components'][code]['origin']] + '{' + code + '}'
    return code


def expression(model, expr):
    if isinstance(expr, str):
        return node(model, expr)
    (op, children), = expr.items()
    word = {'and': ' AND ', 'or': ' OR '}[op]
    parts = [('(' + expression(model, c) + ')') if isinstance(c, dict) else expression(model, c)
             for c in children]
    return word.join(parts)


def cite(source):
    key, _, rest = source.partition(' ')
    return r'\parencite[' + rest.replace(' ', '~') + ']{' + key + '}'


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEAD + text, encoding='utf-8')


def reference_tables(model, out):
    rows = []
    for code, c in model['components'].items():
        rows.append(node(model, code) + ' & ' + tex(c['label']) + ' & ' + c['origin'] + ' & '
                    + tex(c['feature']) + r' \\')
    write(out / 'reference-components.tex', '\n'.join(rows) + '\n\\bottomrule\n')
    rows = []
    for code, c in model['capabilities'].items():
        rows.append(code + ' & ' + tex(c['label']) + ' & ' + tex(c['actor']) + ' & \\texttt{'
                    + c['type'] + '} & ' + expression(model, c['needs']) + r' \\')
    write(out / 'reference-capabilities.tex', '\n'.join(rows) + '\n\\bottomrule\n')
    rows = []
    for code, harm in model['harms'].items():
        for i, p in enumerate(harm['pathways']):
            first = (r'\texttt{' + code + '}') if i == 0 else ''
            tag = r' (\texttt{T-REL})' if p.get('tag') else ''
            cites = ''.join(cite(s) for s in p['sources'])
            rows.append(first + ' & ' + p['id'] + ' & ' + p['capability'] + ' & '
                        + tex(p['consequence']) + tag + ' & ' + p['basis'] + ' & ' + cites + r' \\')
        rows.append(r'\addlinespace[2pt]')
    write(out / 'reference-pathways.tex', '\n'.join(rows[:-1]) + '\n\\bottomrule\n')


def v1_states(record, with_walkthrough):
    """States of the original fixture; v001 evaluated OR+ like OR."""
    return {k: (v.get('with_walkthrough', v['state']) if with_walkthrough else v['state'])
            for k, v in record['components'].items()}


def v1_capabilities(model, states):
    """v001 semantics, kept here only to reproduce the historical result."""
    def evaluate(expr):
        if isinstance(expr, str):
            return states[expr]
        (op, children), = expr.items()
        values = [evaluate(c) for c in children]
        if op == 'and':
            if ev.ABSENT in values:
                return ev.ABSENT
            return ev.PRESENT if all(v == ev.PRESENT for v in values) else ev.UNCERTAIN
        if ev.PRESENT in values:
            return ev.PRESENT
        return ev.ABSENT if all(v == ev.ABSENT for v in values) else ev.UNCERTAIN
    return {k: evaluate(c['needs']) for k, c in model['capabilities'].items()}


def reevaluate(root):
    study = root / '04_Study'
    m1 = ev.load(study / 'Reference-Model/reference_model_v1.yaml')
    m2 = ev.load(study / 'Reference-Model/reference_model_v2.yaml')
    r1 = ev.load(study / 'Instrument-Test/applicability_clue.yaml')
    r2 = ev.load(study / 'Instrument-Test/applicability_clue_v2.yaml')
    s2 = {k: v['state'] for k, v in r2['components'].items()}
    out = {'capabilities': {}, 'pathways': {}}
    for label, wt in (('policy', False), ('with_walkthrough', True)):
        c1 = v1_capabilities(m1, v1_states(r1, wt))
        c2 = ev.capability_states(m2, s2)
        for k in c2:
            out['capabilities'].setdefault(k, {})[label] = {'v1': c1[k], 'v2': c2[k]}
        p2 = ev.pathway_states(m2, s2)
        for h in m1['harms'].values():
            for p in h['pathways']:
                out['pathways'].setdefault(p['id'], {})[label] = {'v1': c1[p['capability']], 'v2': p2[p['id']]}
    out['harms_v2'] = ev.harm_states(m2, s2)
    changed = sorted({k for k, d in out['capabilities'].items() for v in d.values() if v['v1'] != v['v2']})
    lines = ['# Re-evaluation of the instrument-test app under reference model v2', '',
             'Generated by `build_reference.py`. v1: model v1 with the original fixture '
             '(`applicability_clue.yaml`, OR+ read like OR, synthetic walkthrough states). '
             'v2: model v2 with `applicability_clue_v2.yaml` (no synthetic walkthrough states).', '',
             '| Capability | v1 policy | v1 with walkthrough | v2 |', '|---|---|---|---|']
    for k, d in out['capabilities'].items():
        mark = ' **changed**' if k in changed else ''
        lines.append(f"| {k}{mark} | {d['policy']['v1']} | {d['with_walkthrough']['v1']} | {d['policy']['v2']} |")
    lines += ['', '| Pathway | v1 policy | v1 with walkthrough | v2 |', '|---|---|---|---|']
    for k, d in out['pathways'].items():
        if d['policy']['v1'] != d['policy']['v2'] or d['with_walkthrough']['v1'] != d['policy']['v2']:
            lines.append(f"| {k} | {d['policy']['v1']} | {d['with_walkthrough']['v1']} | {d['policy']['v2']} |")
    return out, '\n'.join(lines) + '\n'


def main(root):
    root = Path(root)
    model = ev.load(root / '04_Study/Reference-Model/reference_model_v2.yaml')
    ev.check_model(model)
    reference_tables(model, root / '03_Thesis/tables')
    result, md = reevaluate(root)
    out = Path(__file__).parent / 'output'
    out.mkdir(exist_ok=True)
    (out / 'reevaluation_clue.json').write_text(json.dumps(result, indent=1), encoding='utf-8')
    (out / 'reevaluation_clue.md').write_text(md, encoding='utf-8')
    print(md)


if __name__ == '__main__':
    main(sys.argv[1])
