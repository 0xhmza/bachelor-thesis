import datetime
import hashlib
import html
import json
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIT = ROOT / '01_Literature'
INDEX = LIT / 'catalog' / 'literature-index.json'
STATUS = LIT / 'catalog' / 'reading-status.csv'
README = LIT / 'README.md'
MAP = LIT / 'catalog' / 'Literature-Map.html'
CATALOGUE = LIT / 'catalog' / 'methods-corpus.json'
MANIFEST = ROOT / '01_Literature/catalog/download-status.json'
BIB = ROOT / '_shared/references.bib'
STATUSES = ('to read', 'skimmed', 'read', 'noted')
SYMBOL = {'to read': '☐', 'skimmed': '◐', 'read': '☑', 'noted': '☑'}
FROM_SYMBOL = {'☐': 'to read', '◐': 'skimmed', '☑': 'read'}
FIELDS = ['id', 'collection', 'priority', 'author_year', 'title', 'status', 'note_file', 'changed_on']
EXTRACTOR = 2   # bump when extract() changes, to re-read cached PDFs


def read_json(path, default=None):
    return json.loads(path.read_text(encoding='utf-8-sig')) if path.exists() else default


def slug(value):
    return re.sub(r'[^a-z0-9]+', '_', value.lower()).strip('_')


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rel(path):
    return Path(path).resolve().relative_to(ROOT).as_posix()


# ------------------------------------------------------------------ sources
ACCENT = {"'": '\u0301', '"': '\u0308', '`': '\u0300', '^': '\u0302', '~': '\u0303', 'u': '\u0306', 'c': '\u0327'}


def latex_text(s):
    """BibTeX field -> plain text (quotes, accents, braces, dashes)."""
    s = re.sub(r'\\mkbibquote\{((?:[^{}]|\{[^{}]*\})*)\}', '\u201c\\1\u201d', s)
    s = re.sub(r'\{?\\([\'"`^~uc])\s?\{?(\w)\}?\}?',
               lambda m: unicodedata.normalize('NFC', m.group(2) + ACCENT[m.group(1)]), s)
    s = re.sub(r'\\[a-zA-Z]+\s?', '', s).replace('\\&', '&').replace('--', '\u2013')
    return re.sub(r'\s+', ' ', re.sub(r'[{}]', '', s)).strip()


def norm_title(s):
    """Comparable title: lower-case letters and digits only, subtitle kept."""
    s = unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode().lower()
    return re.sub(r'[^a-z0-9]+', '', s)


def bib_entries():
    text = BIB.read_text(encoding='utf-8')
    out = {}
    for m in re.finditer(r'@\w+\s*\{\s*([^,\s]+)\s*,(.*?)\n\}', text, re.S):
        body = m.group(2)
        def field(name):
            f = re.search(name + r'\s*=\s*\{((?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}', body, re.I)
            return latex_text(f.group(1)) if f else ''
        out[m.group(1)] = {'title': field('title'), 'doi': field('doi').lower(), 'url': field('url'),
                           'year': field('year') or field('date')[:4]}
    return out


def core_rows():
    """Rows of the core reading tables in README.md: key -> (status, author_year, pdf named in row)."""
    rows = {}
    for line in README.read_text(encoding='utf-8').splitlines():
        m = re.match(r'\|\s*([☐◐☑])\s*\|\s*([☑☒])\s*\|\s*`([^`]+)`\s*\|\s*([^|]+)\|', line)
        if m:
            pdf = re.search(r'`([^`]+\.pdf)`', line)
            rows[m.group(3)] = {'status': FROM_SYMBOL[m.group(1)], 'author_year': m.group(4).strip(),
                                'pdf': pdf.group(1) if pdf else None, 'has_pdf': m.group(2) == '☑'}
    return rows


def core_pdf(key, row):
    folder = LIT / 'library'
    if not row.get('has_pdf', True):   # the README marks it missing: do not guess a file from the library
        return None
    if row['pdf'] and (folder / row['pdf']).exists():
        return folder / row['pdf']
    author = re.match(r'[a-z]+', key)
    year = re.search(r'\d{4}', key)
    for p in sorted(folder.glob('*.pdf')):  # surname anywhere (double surnames), plus the year
        name = slug(p.stem)
        if author and author.group(0) in name.replace('_', '') and year and year.group(0)[:3] in name:
            return p
    return None


# ------------------------------------------------------------- extraction
END = re.compile(r'\n\s*(?:\d\.?|I\.?)?\s*(?:INTRODUCTION|Introduction)\b|\b(?:Keywords|KEYWORDS|Key words|Index Terms|'
                 r'INDEX TERMS|CCS CONCEPTS|CCS Concepts|ACM Reference Format|Author Keywords|Additional Key Words)\b')


def extract(pdf):
    """Title-page metadata only: the abstract and keywords as printed, or empty."""
    try:
        import pymupdf
    except ImportError:  # outside the project venv
        return {'abstract': '', 'keywords': '', 'pages': None, 'note': 'PyMuPDF unavailable'}
    try:
        doc = pymupdf.open(pdf)
    except Exception as exc:
        return {'abstract': '', 'keywords': '', 'pages': None, 'note': f'unreadable: {exc.__class__.__name__}'}
    text = '\n'.join(doc[i].get_text() for i in range(min(3, doc.page_count)))
    pages = doc.page_count
    doc.close()
    # ligatures (ﬁ), soft hyphens and line-break hyphenation
    text = unicodedata.normalize('NFKC', text).replace('­\n', '').replace('­ ', '').replace('­', '')
    text = re.sub(r'-\n(?=[a-z])', '', text)
    abstract = ''
    m = re.search(r'(?:^|\n)\s*(?:A\s?B\s?S\s?T\s?R\s?A\s?C\s?T|Abstract|Summary)\b[\s.:—–-]*', text)
    if m:
        rest = text[m.end():]
        e = END.search(rest)
        abstract = rest[:e.start() if e else 2200]
        abstract = re.sub(r'\s+', ' ', abstract).strip()[:2200]
    keywords = ''
    k = re.search(r'(?:Keywords|KEYWORDS|Key words|Index Terms|INDEX TERMS|Author Keywords|Additional Key Words and Phrases)'
                  r'[\s:—–-]*(.{0,400}?)(?:\n\s*\n|ACM Reference|CCS|\n\s*(?:\d\.?\s*)?INTRODUCTION|$)', text, re.S)
    if k:
        keywords = re.sub(r'\s+', ' ', k.group(1)).strip(' .;:')
    if len(abstract) < 120:   # a heading match without real text is no abstract
        abstract = ''
    return {'abstract': abstract, 'keywords': keywords, 'pages': pages,
            'note': '' if abstract else 'no labelled abstract on the first pages'}


# ------------------------------------------------------------------ build
def update(verbose=True):
    bib = bib_entries()
    bib_by_doi = {v['doi']: k for k, v in bib.items() if v['doi']}
    bib_by_url = {v['url']: k for k, v in bib.items() if v['url']}
    bib_by_title = {norm_title(v['title']): k for k, v in bib.items() if len(v['title']) > 12}
    core = core_rows()
    catalogue = read_json(CATALOGUE, {'ranked_doi_records': [], 'official_or_no_doi_resources': []})
    manifest = {str(r['id']): r for r in read_json(MANIFEST, {'records': []})['records']}
    previous = {i['id']: i for i in read_json(INDEX, {'items': []})['items']}
    items = {}

    for key, row in core.items():
        b = bib.get(key, {})
        pdf = core_pdf(key, row)
        items[key] = {'id': key, 'collection': 'core', 'bib_key': key if key in bib else None,
                      'methods_id': None, 'priority': 'core', 'author_year': row['author_year'],
                      'title': b.get('title') or row['author_year'], 'doi': b.get('doi', ''),
                      'url': ('https://doi.org/' + b['doi']) if b.get('doi') else b.get('url', ''),
                      'file': rel(pdf) if pdf else None, 'seed_status': row['status']}
    for work in catalogue['ranked_doi_records'] + catalogue['official_or_no_doi_resources']:
        wid = str(work['id'])
        doi = (work.get('doi') or '').lower()
        title = norm_title(re.sub(r'^.*?\(\d{4}\),\s*', '', work.get('title', '')))
        key = bib_by_doi.get(doi) or bib_by_url.get(work.get('url', '')) or bib_by_title.get(title)
        if key in items:  # same work as a core entry: one item, two identities
            items[key]['methods_id'] = wid
            items[key]['topic'] = work.get('category', 'Official and non-DOI resources')
            items[key]['priority'] = 'core · ' + work.get('priority', '')
            held = manifest.get(wid) or work.get('download') or {}
            if not items[key]['file'] and held.get('downloaded') and held.get('file', '').endswith('.pdf'):
                items[key]['file'] = held['file']
            continue
        record = manifest.get(wid) or work.get('download') or {}   # the catalogue carries each work's local file
        items['M' + wid] = {
            'id': 'M' + wid, 'collection': 'methods', 'bib_key': key, 'methods_id': wid,
            'priority': work.get('priority', ''), 'rank': work.get('rank'),
            'author_year': (f"{work.get('author_label', '')} ({work.get('year', '')})".strip()
                            if work.get('author_label') else ''),
            'title': work.get('title', ''), 'doi': doi, 'topic': work.get('category', 'Official and non-DOI resources'),
            'url': work.get('doi_url') or work.get('url') or work.get('primary_url', ''),
            'file': record['file'] if record.get('downloaded') and record.get('file', '').endswith('.pdf') else None,
            'seed_status': 'to read'}

    extracted = reused = 0
    for item in items.values():
        path = ROOT / item['file'] if item['file'] else None
        if path and path.exists():
            digest = sha256(path)
            old = previous.get(item['id'])
            if old and old.get('sha256') == digest and old.get('extractor') == EXTRACTOR:
                item.update({k: old[k] for k in ('abstract', 'keywords', 'pages', 'note') if k in old})
                reused += 1
            else:
                item.update(extract(path))
                extracted += 1
            item['sha256'] = digest
            item['extractor'] = EXTRACTOR
        else:
            item.update({'abstract': '', 'keywords': '', 'pages': None,
                         'note': 'no local PDF' if not item['file'] else 'file missing'})

    # reading tracker: keep hand-edited statuses, append new works
    rows = {}
    if STATUS.exists():
        with STATUS.open(encoding='utf-8', newline='') as fh:
            rows = {r['id']: r for r in csv.DictReader(fh)}
    today = datetime.date.today().isoformat()
    bad = []
    for item in items.values():
        row = rows.get(item['id'])
        note = LIT / 'notes' / (Path(item['file']).stem + '.md') if item['file'] else None
        if not row:
            row = {'id': item['id'], 'status': item['seed_status'], 'changed_on': today}
        row.update({'collection': item['collection'], 'priority': item['priority'],
                    'author_year': item['author_year'], 'title': item['title'],
                    'note_file': rel(note) if note and note.exists() else ''})
        if row['status'] not in STATUSES:
            bad.append(f"{item['id']}: {row['status']!r}")
            row['status'] = 'to read'
        rows[item['id']] = row
        item['status'] = row['status']
        item.pop('seed_status', None)
    order = sorted(rows.values(), key=lambda r: (r['collection'] != 'core', r['collection'],
                                                 int(re.sub(r'\D', '', r['id']) or 0) if r['id'].startswith('M') else 0,
                                                 r['id']))
    with STATUS.open('w', encoding='utf-8', newline='') as fh:
        w = csv.DictWriter(fh, FIELDS, extrasaction='ignore', lineterminator='\n')
        w.writeheader()
        w.writerows(r for r in order if r['id'] in items)

    # mirror core statuses into the README table
    text = README.read_text(encoding='utf-8')
    def sync(m):
        key = m.group(3)
        return m.group(1) + SYMBOL[items[key]['status']] + m.group(2) + key + m.group(4) if key in items else m.group(0)
    new = re.sub(r'(\|\s*)[☐◐☑](\s*\|\s*[☑☒]\s*\|\s*`)([^`]+)(`)', sync, text)
    if new != text:
        README.write_text(new, encoding='utf-8')

    data = {'generated_on': today,
            'note': 'Generated by scripts/literature_index.py. Abstracts and keywords are copied verbatim from the '
                    'title pages of local PDFs where the paper labels them; empty means not found, not absent. '
                    'Reading status comes from reading-status.csv.',
            'counts': {s: sum(1 for i in items.values() if i['status'] == s) for s in STATUSES},
            'items': sorted(items.values(), key=lambda i: (i['collection'] != 'core', i['id']))}
    data['counts']['with_abstract'] = sum(1 for i in items.values() if i['abstract'])
    data['counts']['total'] = len(items)
    INDEX.write_text(json.dumps(data, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    if verbose:
        print(f"Literature index: {len(items)} works, {data['counts']['with_abstract']} abstracts "
              f"({extracted} read, {reused} cached); status " +
              ', '.join(f"{s}: {data['counts'][s]}" for s in STATUSES) +
              (f"; invalid statuses reset: {', '.join(bad)}" if bad else ''))
    return data


def lookup(data=None):
    """Item lookups for the graph adapter: by bib key and by catalogue id."""
    data = data or read_json(INDEX, {'items': []})
    by_bib, by_work = {}, {}
    for item in data['items']:
        if item.get('bib_key'):
            by_bib[item['bib_key']] = item
        if item.get('methods_id'):
            by_work[item['methods_id']] = item
    return by_bib, by_work


# -------------------------------------------------------------------- map
def build_map(graph_path=ROOT / 'graphify-out/graph.json'):
    """Literature-focused view of the project graph as a self-contained HTML page."""
    g = read_json(graph_path)
    if not g:
        return
    nodes = {n['id']: n for n in g['nodes']}
    links = g.get('links') or g.get('edges') or []
    by_bib, by_work = lookup()

    def chapter_of(nid):
        m = re.match(r'index_03_thesis_(chapters|appendix)_([0-9a-z]+)_', nid)
        return f'index_03_thesis_{m.group(1)}_{m.group(2)}' if m else None

    keep, out_edges = {}, set()
    alias = {}  # methods work -> bib node when they are the same work
    for item in by_work.values():
        if item.get('bib_key') and 'index_bib_' + slug(item['bib_key']) in nodes:
            alias['index_lit_' + slug(item['methods_id'])] = 'index_bib_' + slug(item['bib_key'])
    for e in links:
        if e.get('relation') == 'same_work_as':
            a, b = e['source'], e['target']
            work, bibn = (a, b) if a.startswith('index_lit_') else (b, a)
            alias[work] = bibn

    def add(nid):
        nid = alias.get(nid, nid)
        n = nodes.get(nid)
        if not n:
            return None
        if nid in keep:
            return nid
        kind = ('chapter' if nid.startswith('index_03_thesis_') else
                'decision' if nid.startswith('index_lit_decision_') else
                'topic' if nid.startswith('index_lit_topic_') else
                'rq' if nid.startswith('index_lit_rq') else
                'work')
        label = n.get('label', nid)
        item = None
        if nid.startswith('index_bib_'):
            key = label.split(':', 1)[0]
            item = by_bib.get(key)
        elif kind == 'work':
            item = by_work.get(nid[len('index_lit_'):].upper())
        if kind == 'chapter':
            label = re.sub(r'^\d+_', '', Path(label).stem).replace('_', ' ').title()
        keep[nid] = {'id': nid, 'kind': kind, 'label': label,
                     'title': (item or {}).get('title') or label,
                     'who': (item or {}).get('author_year', ''),
                     # cited sources outside the reading list (laws, guidelines) carry no reading status
                     'status': (item or {}).get('status', 'untracked' if kind == 'work' else ''),
                     'priority': (item or {}).get('priority', ''),
                     'topic': (item or {}).get('topic', ''),
                     'abstract': (item or {}).get('abstract', ''),
                     'keywords': (item or {}).get('keywords', ''),
                     'url': (item or {}).get('url', ''),
                     'file': (item or {}).get('file') or '',
                     'cited': nid.startswith('index_bib_'),
                     'desc': n.get('description', '') if kind in ('decision', 'topic', 'rq') else ''}
        return nid

    for e in links:
        s, t, rel_ = e['source'], e['target'], e.get('relation')
        if rel_ == 'cites' and s.startswith('index_bib_'):  # undirected export may store either way
            s, t = t, s
        if rel_ == 'cites':
            ch = chapter_of(s)
            if ch and t.startswith('index_bib_'):
                chapter_file = next((nid for nid in nodes if nid.startswith(ch) and nid.endswith('_file')), None)
                if chapter_file:
                    a, b = add(chapter_file), add(t)
                    if a and b:
                        out_edges.add((a, b, 'cites'))
        elif rel_ in ('contains', 'recommended_reading', 'informs_rq'):
            if rel_ == 'contains' and not (s.startswith('index_lit_topic_') and t.startswith('index_lit_')):
                continue
            if rel_ == 'informs_rq' and not t.startswith('index_lit_rq'):
                continue
            if s.startswith(('index_lit_copy', 'index_lit_gap')) or t.startswith(('index_lit_copy', 'index_lit_gap')):
                continue
            a, b = add(s), add(t)
            if a and b and a != b:
                out_edges.add((a, b, rel_))
    # core works that are not cited yet still belong on the reading map
    for key, item in by_bib.items():
        nid = 'index_bib_' + slug(key)
        if nid in nodes and item['collection'] == 'core':
            add(nid)

    payload = {'nodes': list(keep.values()),
               'edges': [{'from': a, 'to': b, 'rel': r} for a, b, r in sorted(out_edges)],
               'built': g.get('built_at_commit') or datetime.date.today().isoformat()}
    counts = {s: sum(1 for n in keep.values() if n['kind'] == 'work' and n['status'] == s) for s in STATUSES}
    page = MAP_TEMPLATE.replace('__DATA__', json.dumps(payload, ensure_ascii=False).replace('</', '<\\/'))
    page = page.replace('__COUNTS__', html.escape(' · '.join(f'{v} {k}' for k, v in counts.items())))
    MAP.write_text(page, encoding='utf-8')
    print(f"Literature map: {len(keep)} nodes, {len(out_edges)} edges -> {rel(MAP)}")


