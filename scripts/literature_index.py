"""Literature layer of the project knowledge graph.

    .\\.venv\\Scripts\\python.exe scripts\\literature_index.py      # index + reading tracker
    (also runs automatically inside  .\\graphify.ps1 refresh)

1. 01_Literature/catalog/literature-index.json  (generated; do not edit)
   One item per work: the core reading list (README table, keyed by BibTeX key)
   and the methodology corpus (catalogue ids, prefixed "M"). For every local PDF
   the title page is read with PyMuPDF and the abstract and keywords are taken
   verbatim where the paper labels them; nothing is summarised or invented.
   Results are cached by the file's SHA-256, so unchanged PDFs are not re-read.

2. 01_Literature/catalog/reading-status.csv  (edit the `status` column by hand)
   The single reading tracker for all works: to read | skimmed | read | noted.
   New works are appended automatically; existing statuses are never overwritten.
   The status column of the core table in 01_Literature/README.md is rewritten
   from this file, so the two cannot drift apart.

3. 01_Literature/catalog/Literature-Map.html  (generated by `build_map`, after a graph build)
   Interactive map of thesis chapters, cited works, the methodology corpus,
   meeting decisions and reading status, drawn from graphify-out/graph.json.
"""
from __future__ import annotations

