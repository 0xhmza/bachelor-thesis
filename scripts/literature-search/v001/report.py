"""Write the thesis tables of the literature review (D13) from the frozen collection and the screening file.

    python scripts/literature-search/v001/report.py
    python -I -m unittest discover -s scripts/literature-search/v001/tests

Reads 05_Data/raw/literature-search_2026-10-26/ (records.csv, run.json), the queries in config.json
and 01_Literature/Systematic-Review/screening.csv; writes the table rows to 03_Thesis/tables/:
literature-queries.tex, literature-flow.tex and literature-included.tex. Standard library only.
"""
import csv, json, re
from collections import Counter
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[3]
RAW = ROOT / '05_Data/raw/literature-search_2026-10-26'
SCREENING = ROOT / '01_Literature/Systematic-Review/screening.csv'
TABLES = ROOT / '03_Thesis/tables'
CONFIG = Path(__file__).resolve().parent / 'config.json'
HEADER = '% Generated by scripts/literature-search/v001/report.py from {}; do not edit by hand.\n'
CRITERIA = ['I1', 'I2', 'I3', 'I4']
EXCLUSIONS = ['E1', 'E2', 'E3', 'E4', 'E5']


def tex(text):
    """Escape LaTeX specials; straight double quotes become \\enquote{...}."""
    text = text.replace('\\', '\0')
    for char in '&%$#_{}':
        text = text.replace(char, '\\' + char)
    text = text.replace('~', '\\textasciitilde{}').replace('^', '\\textasciicircum{}')
    text = text.replace('\0', '\\textbackslash{}')
    text = re.sub(r'"([^"]*)"', r'\\enquote{\1}', text)
    return text.replace('"', '\u201d')  # an unpaired straight quote closes a typographic opening one


def clean_title(title):
    """Database titles sometimes carry escaped or wrapping straight quotes around a quoted title."""
    title = ' '.join(title.replace('\\"', '"').split())
    if len(title) > 1 and title[0] == '"' and title[-1] == '"':
        title = title[1:-1]
    return title


def thousands(n):
    return f'{n:,}'.replace(',', '{,}')


def query_rows(config):
    rows = [f"Domain & -- & {tex(config['domain'])} \\\\"]
    for q in config['queries']:
        query = tex(q['query'].replace('{domain}', 'DOMAIN'))
        rows.append(f"{q['id']} & {q['from'][:4]}--{config['searched_until'][:4]} & {query} \\\\")
    return rows


def flow_rows(run, screening):
    counts = run['hits_per_query_and_database']
    rows = []
    for q in ['Q1', 'Q2', 'Q3', 'Q4']:
        rows.append(f"{q} & {thousands(counts[q + ' OpenAlex'])} & {thousands(counts[q + ' Semantic Scholar'])} \\\\")
    rows.append(f"Manually added & \\multicolumn{{2}}{{c}}{{{counts['Manually added']}}} \\\\")
    rows.append('\\midrule')
    codes = Counter(row['code'] for row in screening)
    stages = [('Hits', run['hits']), ('Records after removing duplicates', run['records_after_deduplication']),
              ('Removed by the citation filter', run['removed_by_citation_filter']),
              ('Records screened (titles and abstracts)', run['records_for_screening'])]
    stages += [(f'Excluded, {code}', codes[code]) for code in EXCLUSIONS]
    stages += [(f'Included, {code}', codes[code]) for code in CRITERIA]
    stages.append(('Included in total', sum(codes[c] for c in CRITERIA)))
    rows += [f"{label} & \\multicolumn{{2}}{{c}}{{{thousands(n)}}} \\\\" for label, n in stages]
    return rows


def included_rows(screening):
    included = [r for r in screening if r['decision'] == 'include']
    included.sort(key=lambda r: (r['code'], r['year'], r['first_author'].split()[-1] if r['first_author'] else ''))
    rows = []
    for n, r in enumerate(included, 1):
        author = r['first_author'].split()[-1] if r['first_author'] else '--'
        if r['doi']:
            link = f"\\href{{https://doi.org/{r['doi']}}}{{\\nolinkurl{{{tex(r['doi'])}}}}}"
        else:  # the host as link text: database page IDs are too long to break in the column
            url = r['url'].replace('%', '\\%').replace('#', '\\#')
            link = f"\\href{{{url}}}{{{tex(urlsplit(r['url']).netloc.removeprefix('www.'))}}}"
        rows.append(f"{n} & {r['code']} & {tex(author)} & {r['year']} & {tex(clean_title(r['title']))} & {link} \\\\")
    return rows


def write(name, rows, source, last_rule=False):
    """last_rule: end with \\bottomrule, since a rule after \\input inside a tabular meets an open cell."""
    rows = rows + ['\\bottomrule'] if last_rule else rows
    (TABLES / name).write_text(HEADER.format(source) + '\n'.join(rows) + '\n', encoding='utf-8')


def main():
    config = json.loads(CONFIG.read_text(encoding='utf-8'))
    run = json.loads((RAW / 'run.json').read_text(encoding='utf-8'))
    screening = list(csv.DictReader(open(SCREENING, encoding='utf-8')))
    assert len(screening) == run['records_for_screening'], 'screening.csv does not match the frozen collection'
    write('literature-queries.tex', query_rows(config), 'scripts/literature-search/v001/config.json', last_rule=True)
    write('literature-flow.tex', flow_rows(run, screening), 'the search of 2026-10-26 and its screening', last_rule=True)
    write('literature-included.tex', included_rows(screening), 'the search of 2026-10-26 and its screening')
    print(Counter(r['code'] for r in screening))


if __name__ == '__main__':
    main()
