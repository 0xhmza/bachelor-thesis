"""Reading aid for screening; it decides nothing.

    python scripts/literature-search/v003/show.py batch NAME [SOURCE] [N]   # next N undecided records (of SOURCE)
    python scripts/literature-search/v003/show.py abstracts NAME NUM [NUM ...]  # abstracts of numbered records
    python scripts/literature-search/v003/show.py expand                    # decisions/raw/*.txt -> decisions/title.csv

A batch prints `number|year|venue|title` and saves decisions/batches/NAME.json (number -> record identifier). The
decisions for a batch are written by hand to decisions/raw/NAME.txt, one line per record: `number code [note]`, where
code is a rule R1-R6 (excluded at title/abstract), `ft` (passes to full text) or `ft:LQ1;LQ2` (with the
sub-questions). `expand` turns all raw files into decisions/title.csv keyed by identifier.
"""
import csv, json, sys

import lit

ROOT = lit.HERE.parents[2]
RECORDS = lit.HERE / 'output' / 'records.csv'
DEC = ROOT / '01_Literature' / 'Literature-Review' / 'decisions'


def records():
    return list(csv.DictReader(open(RECORDS, encoding='utf-8')))


def short(text, n):
    text = ' '.join((text or '').split())
    return text if len(text) <= n else text[:n - 1] + '~'


def decided():
    done = set()
    for f in (DEC / 'batches').glob('*.json'):
        done.update(json.loads(f.read_text(encoding='utf-8')).values())
    return done


def batch(name, source=None, n=150):
    done = decided()
    rs = [r for r in records() if not set(r['ids'].split()) & done and (not source or source in r['sources'].split(';'))]
    chosen = rs[:n]
    (DEC / 'batches').mkdir(parents=True, exist_ok=True)
    path = DEC / 'batches' / f'{name}.json'
    if path.exists():
        raise SystemExit(f'{path} exists')
    path.write_text(json.dumps({str(i): r['ids'].split()[0] for i, r in enumerate(chosen, 1)}, indent=0), encoding='utf-8')
    for i, r in enumerate(chosen, 1):
        print(f"{i}|{r['year']}|{short(r['venue'], 22)}|{short(r['title'], 150)}")
    print(f'-- {len(chosen)} shown, {len(rs) - len(chosen)} more undecided')


def abstracts(name, nums):
    m = json.loads((DEC / 'batches' / f'{name}.json').read_text(encoding='utf-8'))
    by_key = {k: r for r in records() for k in r['ids'].split()}
    for n in nums:
        r = by_key[m[n]]
        print(f"{n}|{r['year']}|{short(r['venue'], 30)}|{r['title']}\n    {short(r['abstract'], 700) or '(no abstract)'}")


def expand():
    rows = []
    for raw in sorted((DEC / 'raw').glob('*.txt')):
        m = json.loads((DEC / 'batches' / f'{raw.stem}.json').read_text(encoding='utf-8'))
        seen = set()
        for line in raw.read_text(encoding='utf-8').splitlines():
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            num, code, *note = line.split(maxsplit=2)
            if num not in m:
                raise SystemExit(f'{raw.name}: no record {num}')
            seen.add(num)
            if code.startswith('ft'):
                rows.append([m[num], 'in', code[3:] if ':' in code else '', ' '.join(note)])
            else:
                rows.append([m[num], 'ex', code, ' '.join(note)])
        missing = set(m) - seen
        if missing:
            raise SystemExit(f'{raw.name}: no decision for {sorted(missing, key=int)[:10]}')
    with open(DEC / 'title.csv', 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['# generated by show.py expand from decisions/raw and decisions/batches'])
        w.writerows(rows)
    print(len(rows), 'decisions')


def main(argv):
    if argv[0] == 'batch':
        batch(argv[1], argv[2] if len(argv) > 2 and argv[2] != '-' else None, int(argv[3]) if len(argv) > 3 else 150)
    elif argv[0] == 'abstracts':
        abstracts(argv[1], argv[2:])
    elif argv[0] == 'expand':
        expand()


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main(sys.argv[1:])
