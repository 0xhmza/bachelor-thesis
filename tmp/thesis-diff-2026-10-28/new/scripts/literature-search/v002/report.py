"""Thesis tables and figures of the literature review v002 (D14), generated from the search and screening files.

    python scripts/literature-search/v002/report.py

Reads output/run-*.json, output/ieee-raw.json, output/merge.json, output/screening.json,
01_Literature/Literature-Review/screening.csv and extraction.csv. Writes 03_Thesis/tables/literature-*.tex and
03_Thesis/figures/literature-*.tex (TikZ and pgfplots code). Every number in them comes from these files.
Standard library only.
"""
import csv, json, re
from collections import Counter

import lit

ROOT = lit.HERE.parents[2]
OUT = lit.HERE / 'output'
LR = ROOT / '01_Literature' / 'Literature-Review'
TABLES, FIGURES = ROOT / '03_Thesis' / 'tables', ROOT / '03_Thesis' / 'figures'
HEAD = '% Generated by scripts/literature-search/v002/report.py from the frozen search and the screening log; do not edit.\n'
DB = ['PubMed', 'IEEE Xplore', 'arXiv', 'ACL Anthology']
VENUES = ['PoPETs', 'USENIX Security', 'SOUPS', 'CCS', 'IEEE S&P', 'NDSS', 'CHI', 'CSCW']
OTHER = ['Citation searching', 'Thesis citation', 'Methods Digest']
LQS = ['LQ1', 'LQ2', 'LQ3', 'LQ4']
LQ_NAME = {'LQ1': 'LQ1 harms', 'LQ2': 'LQ2 communication', 'LQ3': 'LQ3 language models', 'LQ4': 'LQ4 framing'}
SHADE = {'LQ1': 'primary!80', 'LQ2': 'accent!75', 'LQ3': 'linkblue!50', 'LQ4': 'muted!40'}


def tex(s):
    s = str(s)
    for a, b in (('\\', r'\textbackslash{}'), ('&', r'\&'), ('%', r'\%'), ('$', r'\$'), ('#', r'\#'), ('_', r'\_'),
                 ('{', r'\{'), ('}', r'\}'), ('~', r'\textasciitilde{}'), ('^', r'\textasciicircum{}')):
        s = s.replace(a, b)
    return s


def num(n):
    return f'{n:,}'.replace(',', '{,}')


def write(path, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEAD + body, encoding='utf-8')


def load():
    runs = {p.stem[4:]: json.loads(p.read_text(encoding='utf-8')) for p in OUT.glob('run-*.json')}
    ieee = json.loads((OUT / 'ieee-raw.json').read_text(encoding='utf-8'))
    merge = json.loads((OUT / 'merge.json').read_text(encoding='utf-8'))
    screen = json.loads((OUT / 'screening.json').read_text(encoding='utf-8'))
    rows = list(csv.DictReader(open(LR / 'screening.csv', encoding='utf-8')))
    ext = {r['id']: r for r in csv.DictReader(open(LR / 'extraction.csv', encoding='utf-8'))}
    return runs, ieee, merge, screen, rows, ext


def passed(rows):
    return [r for r in rows if r['decision'] in ('include', 'pending')]


# --- Tables ----------------------------------------------------------------------------------------------------

def sources_table(runs, ieee, merge, rows):
    ps = merge['per_source']
    ok = Counter(s for r in passed(rows) for s in r['sources'].split(';'))
    def strands(qs):
        return ', '.join(f"{k}~{num(v)}" for k, v in qs.items())
    lines = []
    for name, key, field in (('PubMed', 'pubmed', 'title, abstract'), ('arXiv', 'arxiv', 'title, abstract$^a$'),
                             ('ACL Anthology', 'acl', 'title, abstract$^a$')):
        qs = {k: v['count'] for k, v in runs[key]['queries'].items()}
        lines.append((name, 'database', field, strands(qs), name))
    lines.insert(1, ('IEEE Xplore', 'database', 'title, abstract', strands({k: v['total'] for k, v in ieee['log'].items()}), 'IEEE Xplore'))
    out = []
    for name, kind, field, hits, src in lines:
        out.append(rf"{tex(name)} & {kind} & {field} & {hits} & {num(ps[src]['records'])} & {num(ps[src]['only_here'])} & {num(ok[src])} \\")
    out.append(r'\midrule')
    for v in VENUES:
        info = runs['venues']['venues'][v]
        field = 'title, abstract$^a$' if info['with_abstract'] > info['papers'] / 2 else 'title$^{a,b}$'
        out.append(rf"{tex(v)} & venue & {field} & {num(info['papers'])} listed & {num(ps[v]['records'])} & {num(ps[v]['only_here'])} & {num(ok[v])} \\")
    out.append(r'\midrule')
    cit = runs['citations']
    out.append(rf"Citation searching & other & references, citing works & {num(cit['dois'])} DOIs & {num(ps['Citation searching']['records'])} & {num(ps['Citation searching']['only_here'])} & {num(ok['Citation searching'])} \\")
    out.append(rf"Thesis citations & other & -- & {num(merge['cited_keys'])} keys & {num(ps['Thesis citation']['records'])} & {num(ps['Thesis citation']['only_here'])} & {num(ok['Thesis citation'])} \\")
    out.append(rf"Methods Digest & other & -- & 116 papers & {num(ps['Methods Digest']['records'])} & {num(ps['Methods Digest']['only_here'])} & {num(ok['Methods Digest'])} \\")
    write(TABLES / 'literature-sources.tex', '\n'.join(out) + '\n\\bottomrule\n')


def groups_table(config):
    out = []
    for g in ['D', 'P', 'H', 'C', 'T', 'L', 'A', 'F']:
        out.append(rf"{g} & {tex(config['groups'][g]['name'])} & \footnotesize {tex(', '.join(config['groups'][g]['terms']))} \\")
    write(TABLES / 'literature-groups.tex', '\n'.join(out) + '\n\\bottomrule\n')


def strings_appendix(runs, ieee, config):
    def block(title, text):
        return (f"\\paragraph{{{title}}}\n\\begin{{lstlisting}}[breaklines=true, breakatwhitespace=false, "
                f"columns=fullflexible, basicstyle=\\ttfamily\\scriptsize, numbers=none, frame=none, "
                f"literate={{ä}}{{{{\\\"a}}}}1]\n{text}\n\\end{{lstlisting}}\n")  # listings reads bytes, not UTF-8
    out = []
    pm = runs['pubmed']
    for s, q in pm['queries'].items():
        out.append(block(f"PubMed, {s}. Searched {pm['searched_at']}; publication date {q['from']} to "
                         f"{config['period']['until']}; {q['count']} records", q['query']))
    for s, q in ieee['log'].items():
        out.append(block(f"IEEE Xplore, {s}. Retrieved {ieee['retrieved_at'][:16].replace('T', ' ')} UTC; years "
                         f"{q['range'][:9].replace('_', '--')}; {q['total']} records", q['query']))
    ax = runs['arxiv']
    out.append(block(f"arXiv, anchor queries. Searched {ax['searched_at']}; submitted {config['period']['from']} to "
                     f"{config['period']['until']}; {len(ax['anchors'])} queries; pool of {ax['pool']} records",
                     '\n'.join(f'{q}   [{n}]' for q, n in ax['anchors'].items())))
    acl = runs['acl']
    out.append(block(f"Local strands (arXiv pool, ACL Anthology file of {acl['entries']} entries, venue lists)",
                     '\n'.join(f"{s['id']} = " + ' AND '.join(s['groups']) + f" (from {s['from']})" for s in config['strands'][:4])
                     + '\nSecurity and privacy venues: D OR S3 OR S4\nCHI and CSCW, with abstract: S1 OR S2 OR S3 OR S4'
                     + '\nCHI and CSCW, title only: (D AND P) OR (D AND H) OR (D AND C) OR (T AND L) OR (T AND F)'))
    write(TABLES / 'literature-strings.tex', '\n'.join(out))


def screening_table(screen):
    out = []
    for f in screen['funnel']:
        if f['rule'] == 'R7':
            out.append(r'\midrule')
            out.append(rf"-- & awaiting full text (not an exclusion) & {num(screen['funnel'][5]['remaining'])} & "
                       rf"\multicolumn{{1}}{{r}}{{({num(screen['pending'])})}} & {num(f['assessed'])} & -- \\")
        out.append(rf"{f['rule']} & {tex(f['text'])} & {num(f['assessed'])} & {num(f['excluded'])} & "
                   rf"{num(f['remaining'])} & {f['percent']:.1f} \\")
    write(TABLES / 'literature-screening.tex', '\n'.join(out) + '\n\\bottomrule\n')


def prov(r):
    s = set(r['sources'].split(';'))
    return ''.join(c for c, test in (('B', s & set(DB)), ('V', s & set(VENUES)), ('C', 'Citation searching' in s),
                                     ('T', 'Thesis citation' in s), ('D', 'Methods Digest' in s)) if test)


def surname(name):
    name = re.sub(r'[{}]', '', name or '').strip()
    return (name.split()[-1] if ' ' in name and ',' not in name else name.split(',')[0]) or '--'


def inventory(rows):
    def line(no, code, r, cite=False):
        who = tex(surname(r['first_author'])) + (rf"\,\cite{{{r['bibkey']}}}" if cite and r['bibkey'] else '')
        return rf"{no} & {code} & {who} & {r['year'] or '--'} & {tex(r['title'])} & {prov(r)} \\"
    out = []  # the first group heading stands in F_literature.tex: a row cannot start with \input and \multicolumn
    review = sorted((r for r in rows if r['collection'] == 'review'), key=lambda r: (r['code'], r['year'], surname(r['first_author'])))
    out += [line(i, r['code'].replace(';', ', '), r, cite=True) for i, r in enumerate(review, 1)]
    out += [r'\midrule', r'\multicolumn{6}{@{}l}{\textbf{Contextual collection (cited in the thesis, outside the criteria)}} \\']
    context = sorted((r for r in rows if r['collection'] == 'contextual'), key=lambda r: (r['code'], r['year'], surname(r['first_author'])))
    out += [line(f'C{i}', r['code'], r, cite=True) for i, r in enumerate(context, 1)]
    out += [r'\midrule', r'\multicolumn{6}{@{}l}{\textbf{Passed title and abstract, awaiting full text}} \\']
    pending = sorted((r for r in rows if r['collection'] == 'awaiting full text'), key=lambda r: (r['code'], r['year'], surname(r['first_author'])))
    out += [line(f'P{i}', r['code'].replace(';', ', '), r, cite=True) for i, r in enumerate(pending, 1)]
    write(TABLES / 'literature-included.tex', '\n'.join(out) + '\n')


