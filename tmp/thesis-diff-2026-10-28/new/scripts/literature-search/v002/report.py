def flow_figure(merge, screen, rows):
    ps = merge['per_source']
    db = sum(ps[s]['records'] for s in DB)
    ven = sum(ps[s]['records'] for s in VENUES)
    search = merge['records_from_searches']
    other = [r for r in rows if not set(r['routes'].split(';')) & {'database', 'venue'}]
    by = Counter(s for r in other for s in r['sources'].split(';') if s in OTHER)
    f = {x['rule']: x for x in screen['funnel']}
    ta = sum(f[k]['excluded'] for k in ['R1', 'R2', 'R3', 'R4', 'R5', 'R6'])
    ft = f['R7']['excluded'] + f['R8']['excluded']
    body = rf"""\begin{{tikzpicture}}[font=\footnotesize, node distance=5mm and 7mm,
  box/.style={{draw=primary, fill=primary!5, rounded corners=1.5pt, align=left, text width=62mm, inner sep=3pt}},
  side/.style={{draw=muted, fill=white, rounded corners=1.5pt, align=left, text width=52mm, inner sep=3pt}},
  stage/.style={{font=\scriptsize\bfseries, text=primary, rotate=90, anchor=south}},
  arr/.style={{-{{Stealth[length=1.5mm]}}, semithick, accentdark}}]
\node[box] (db) {{\textbf{{Database searches:}} {num(db)} records\\
  PubMed {num(ps['PubMed']['records'])}, IEEE Xplore {num(ps['IEEE Xplore']['records'])},
  arXiv {num(ps['arXiv']['records'])}, ACL Anthology {num(ps['ACL Anthology']['records'])}\\[2pt]
  \textbf{{Venue searches:}} {num(ven)} records\\
  {', '.join(f"{tex(v)} {num(ps[v]['records'])}" for v in VENUES)}}};
\node[side, right=of db] (oth) {{\textbf{{Other methods:}} {num(len(other))} records found\\ by no search\\
  citation searching {num(by['Citation searching'])}, thesis\\ citations {num(by['Thesis citation'])}, Methods Digest {num(by['Methods Digest'])}$^{{*}}$}};
\node[box, below=of db] (dd) {{Duplicates across sources removed: {num(db + ven - search)}\\
  Records from searches: {num(search)}}};
\node[box, below=8mm of dd] (ta) {{\textbf{{Screened on title and abstract:}} {num(screen['records'])}}};
\node[side, right=of ta] (tax) {{Excluded (R1--R6): {num(ta)}\\
  {', '.join(f"{k} {num(f[k]['excluded'])}" for k in ['R1', 'R2', 'R3'])},\\
  {', '.join(f"{k} {num(f[k]['excluded'])}" for k in ['R4', 'R5', 'R6'])}}};
\node[box, below=of ta] (pass) {{Passed to full text: {num(screen['title_stage_passed'])}}};
\node[side, right=of pass] (pend) {{Awaiting full text: {num(screen['pending'])}\\
  {', '.join(f"{q} {num(screen['pending_per_lq'][q])}" for q in LQS)}$^{{\dagger}}$}};
\node[box, below=of pass] (ftb) {{\textbf{{Full texts assessed:}} {num(screen['fulltext_assessed'])}}};
\node[side, right=of ftb] (ftx) {{Excluded (R7--R8): {num(ft)}\\ R7 {num(f['R7']['excluded'])}, R8 {num(f['R8']['excluded'])}}};
\node[box, below=of ftb, fill=accent!10, draw=accent] (inc) {{\textbf{{Review evidence:}} {num(screen['included'])} studies\\
  {', '.join(f"{q} {num(screen['per_lq'][q])}" for q in LQS)}$^{{\dagger}}$}};
\node[side, right=of inc, draw=accent] (ctx) {{\textbf{{Contextual collection:}} {num(screen['contextual'])}\\ cited works excluded by R1--R8}};
\draw[arr] (db) -- (dd);
\draw[arr] (dd) -- (ta);
\draw[arr] (oth.south) |- ([yshift=4mm]ta.north) -- (ta.north);
\draw[arr] (ta) -- (tax); \draw[arr] (ta) -- (pass); \draw[arr] (pass) -- (pend); \draw[arr] (pass) -- (ftb);
\draw[arr] (ftb) -- (ftx); \draw[arr] (ftb) -- (inc);
\draw[arr, dashed, muted] (tax.east) -- ++(3mm,0) |- (ctx.east);
\node[stage] at ([xshift=-2mm]db.west) {{Identification}};
\node[stage] at ([xshift=-2mm]dd.west) {{Duplicates}};
\node[stage] at ([xshift=-2mm, yshift=-4mm]pass.west) {{Screening}};
\node[stage] at ([xshift=-2mm]inc.west) {{Included}};
\end{{tikzpicture}}
"""
    write(FIGURES / 'literature-flow.tex', body)


def hbar(name, labels, values, xlabel, ylabel, notes, height, fill='primary!70', draw='primary'):
    coords = ' '.join('(%s,{%s})' % (v, tex(l)) for l, v in zip(reversed(labels), reversed(values)))
    xmax = max(values) * 1.5 + 1
    nodes = '\n'.join(rf"\node[anchor=west, font=\scriptsize, text=muted] at (axis cs:{v},{{{tex(l)}}}) {{\,{n}}};"
                      for l, v, n in zip(labels, values, notes))
    body = rf"""\begin{{tikzpicture}}
\begin{{axis}}[xbar, width=0.78\textwidth, height={height}mm, bar width=6.5pt, xmin=0, xmax={xmax:.0f},
  symbolic y coords={{{','.join('{' + tex(l) + '}' for l in reversed(labels))}}}, ytick=data,
  y tick label style={{font=\footnotesize}}, x tick label style={{font=\footnotesize, /pgf/number format/1000 sep={{\,}}}},
  xlabel={{{xlabel}}}, ylabel={{{ylabel}}}, label style={{font=\footnotesize}},
  axis x line*=bottom, axis y line*=left, xmajorgrids, grid style={{muted!25}}, enlarge y limits={0.5 / len(labels):.3f}]
\addplot[fill={fill}, draw={draw}] coordinates {{{coords}}};
{nodes}
\end{{axis}}
\end{{tikzpicture}}
"""
    write(FIGURES / name, body)


def exclusion_figure(screen):
    fun = screen['funnel']
    hbar('literature-exclusions.tex', [f"{x['rule']} {x['text']}" for x in fun], [x['excluded'] for x in fun],
         'Records excluded (primary reason only)', 'Exclusion rule, in the order applied',
         [f"{num(x['excluded'])} of {num(x['assessed'])} ({x['percent']:.1f}\\,\\%)" for x in fun], 70)


def source_figure(merge, rows):
    ps = merge['per_source']
    names = DB + VENUES + OTHER
    ok = Counter(s for r in passed(rows) for s in r['sources'].split(';'))
    labels = ','.join('{' + tex(n) + '}' for n in reversed(names))
    only = ' '.join('(%d,{%s})' % (ps[n]['only_here'], tex(n)) for n in reversed(names))
    shared = ' '.join('(%d,{%s})' % (ps[n]['records'] - ps[n]['only_here'], tex(n)) for n in reversed(names))
    nodes = '\n'.join(rf"\node[anchor=west, font=\scriptsize, text=accentdark] at (axis cs:{ps[n]['records']},{{{tex(n)}}}) {{\,{ok[n]}}};"
                      for n in names)
    body = rf"""\begin{{tikzpicture}}
\begin{{axis}}[xbar stacked, width=0.8\textwidth, height=92mm, bar width=6pt, xmin=0, xmax={max(ps[n]['records'] for n in names) * 1.12:.0f},
  symbolic y coords={{{labels}}}, ytick=data, y tick label style={{font=\footnotesize}},
  x tick label style={{font=\footnotesize, /pgf/number format/1000 sep={{\,}}}},
  xlabel={{Records after removing duplicates within the source}}, ylabel={{Source}}, label style={{font=\footnotesize}},
  axis x line*=bottom, axis y line*=left, xmajorgrids, grid style={{muted!25}}, enlarge y limits=0.04,
  legend style={{font=\scriptsize, draw=none, at={{(0.98,0.03)}}, anchor=south east}}, legend cell align=left]
\addplot[fill=primary!75, draw=primary] coordinates {{{only}}};
\addplot[fill=primary!18, draw=primary!60] coordinates {{{shared}}};
\legend{{found by this source only, also found by another source}}
{nodes}
\end{{axis}}
\end{{tikzpicture}}
"""
    write(FIGURES / 'literature-sources.tex', body)


def year_figure(rows):
    ok = passed(rows)
    years = list(range(2014, 2027))
    plots = []
    for q in LQS:  # each record counted once, under its first sub-question
        c = Counter(int(r['year']) for r in ok if r['year'] and r['code'].split(';')[0] == q)
        plots.append(rf"\addplot[fill={SHADE[q]}, draw=black!35] coordinates {{{' '.join(f'({y},{c[y]})' for y in years)}}};")
    rev = Counter(int(r['year']) for r in rows if r['collection'] == 'review' and r['year'])
    body = rf"""\begin{{tikzpicture}}
\begin{{axis}}[ybar stacked, width=0.92\textwidth, height=64mm, bar width=9pt, ymin=0,
  xtick={{{','.join(map(str, years))}}}, x tick label style={{font=\footnotesize, rotate=45, anchor=east, /pgf/number format/1000 sep={{}}}},
  y tick label style={{font=\footnotesize}}, xlabel={{Year of publication}}, ylabel={{Records}}, label style={{font=\footnotesize}},
  axis x line*=bottom, axis y line*=left, ymajorgrids, grid style={{muted!25}}, enlarge x limits=0.05,
  legend style={{font=\scriptsize, draw=none, at={{(0.02,0.98)}}, anchor=north west}}, legend cell align=left]
{chr(10).join(plots)}
\legend{{{', '.join(LQ_NAME[q] for q in LQS)}}}
\end{{axis}}
\end{{tikzpicture}}
"""
    write(FIGURES / 'literature-years.tex', body)  # review evidence per year: tables/literature-years-review.tex
    write(TABLES / 'literature-years-review.tex', ' & '.join(str(rev[y]) for y in years) + r' \\' + '\n')


def venue_figure(rows, ext):
    ok = passed(rows)
    kinds = ['Security and privacy venue', 'HCI venue', 'Health or medical journal', 'NLP venue', 'Law or social science',
             'Other computing venue', 'Preprint']
    rev = Counter(ext[r['id']]['venue_type'] for r in ok if r['decision'] == 'include')
    pen = Counter(ext[r['id']]['venue_type'] for r in ok if r['decision'] == 'pending')
    kinds = [k for k in kinds if rev[k] + pen[k]]
    labels = ','.join('{' + tex(k) + '}' for k in reversed(kinds))
    body = rf"""\begin{{tikzpicture}}
\begin{{axis}}[xbar stacked, width=0.75\textwidth, height={20 + 8 * len(kinds)}mm, bar width=7pt, xmin=0,
  xmax={max(rev[k] + pen[k] for k in kinds) * 1.15:.0f}, symbolic y coords={{{labels}}}, ytick=data,
  y tick label style={{font=\footnotesize}}, x tick label style={{font=\footnotesize}}, xlabel={{Records}}, ylabel={{Venue type}},
  label style={{font=\footnotesize}}, axis x line*=bottom, axis y line*=left, xmajorgrids, grid style={{muted!25}},
  enlarge y limits={0.5 / len(kinds):.3f}, legend style={{font=\scriptsize, draw=none, at={{(0.98,0.03)}}, anchor=south east}}, legend cell align=left]
\addplot[fill=accent!80, draw=accent] coordinates {{{' '.join('(%d,{%s})' % (rev[k], tex(k)) for k in reversed(kinds))}}};
\addplot[fill=accent!20, draw=accent!60] coordinates {{{' '.join('(%d,{%s})' % (pen[k], tex(k)) for k in reversed(kinds))}}};
\legend{{review evidence, awaiting full text}}
\end{{axis}}
\end{{tikzpicture}}
"""
    write(FIGURES / 'literature-venues.tex', body)


def heatmap(name, rows_labels, cols_labels, counts, xlabel, ylabel, label_width=34):
    maxv = max([1] + list(counts.values()))
    out = [r'\begin{tikzpicture}[font=\footnotesize, x=9.5mm, y=-6.2mm]']
    for j, col in enumerate(cols_labels):
        out.append(rf"\node[rotate=45, anchor=south west, inner sep=1pt, font=\scriptsize] at ({j + 0.3},-0.05) {{{tex(col)}}};")
    for i, row in enumerate(rows_labels):
        out.append(rf"\node[anchor=east, font=\scriptsize] at (-0.1,{i + 0.5}) {{{tex(row)}}};")
        for j, col in enumerate(cols_labels):
            v = counts.get((row, col), 0)
            shade = int(10 + 75 * v / maxv) if v else 0
            out.append(rf"\filldraw[fill={'primary!%d' % shade if v else 'white'}, draw=muted!35] ({j},{i}) rectangle ({j + 1},{i + 1});")
            if v:
                out.append(rf"\node[text={'white' if shade > 50 else 'black'}, font=\scriptsize] at ({j + 0.5},{i + 0.5}) {{{v}}};")
    out.append(rf"\node[anchor=north, font=\footnotesize] at ({len(cols_labels) / 2},{len(rows_labels) + 0.2}) {{{xlabel}}};")
    out.append(rf"\node[anchor=south, rotate=90, font=\footnotesize] at (-{label_width / 9.5:.2f},{len(rows_labels) / 2}) {{{ylabel}}};")
    out.append(r'\end{tikzpicture}')
    write(FIGURES / name, '\n'.join(out) + '\n')


def split(v):
    return [x for x in (v or '').split(';') if x]


def map_figures(rows, ext, config):
    m = config['extraction']
    surfaces = m['surface'] + ['Not stated']
    ok = {r['id'] for r in passed(rows)}
    c1 = Counter((d, s) for rid, e in ext.items() if rid in ok for d in split(e['domain']) for s in split(e['surface']))
    heatmap('literature-map-surfaces.tex', m['domain'], surfaces, c1, 'Material or surface studied (title and abstract)', 'App domain')
    rev = {r['id'] for r in rows if r['collection'] == 'review'}
    c2 = Counter((a, d) for rid, e in ext.items() if rid in rev for a in split(e['rq']) for d in split(e['domain']))
    heatmap('literature-map-rq.tex', m['rq'], m['domain'], c2, 'App domain', 'Part of the thesis RQ', 40)


def main():
    config = lit.load_config()
    runs, ieee, merge, screen, rows, ext = load()
    sources_table(runs, ieee, merge, rows)
    groups_table(config)
    strings_appendix(runs, ieee, config)
    screening_table(screen)
    inventory(rows)
    flow_figure(merge, screen, rows)
    exclusion_figure(screen)
    source_figure(merge, rows)
    year_figure(rows)
    venue_figure(rows, ext)
    map_figures(rows, ext, config)
    print('tables and figures written')


if __name__ == '__main__':
    main()
