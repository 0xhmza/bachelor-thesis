"""Collect the finished PDFs into build/deliverables/ and write an index.

    build/deliverables/
        00_Methods-Digest_complete.pdf
        by-stage/1_S_Scope-and-definitions.pdf ... 9_R_Reporting.pdf
        README.md                                   (what each file contains, size, pages)

Run after build_digest.py (complete volume) and build_digest.py --all-stages.
"""
from pathlib import Path
import shutil

import fitz

HERE = Path(__file__).resolve().parent.parent
BUILD = HERE / "build"
OUT = BUILD / "deliverables"

NAMES = {
    "S": "Scope and definitions", "A": "App search and selection", "D": "Material capture",
    "W": "Walkthrough", "C": "Codebook and pilot", "I": "Two-coder comparison",
    "L": "LLM feasibility", "H": "Harm tree", "R": "Reporting",
}
ORDER = "SADWCILHR"


def info(p: Path) -> tuple[str, int]:
    doc = fitz.open(p)
    return f"{p.stat().st_size / 1e6:.1f} MB", doc.page_count


def main():
    OUT.mkdir(exist_ok=True)
    (OUT / "by-stage").mkdir(exist_ok=True)
    rows = []
    full = BUILD / "Methods-Digest.pdf"
    if full.exists() and full.stat().st_size > 0:
        dst = OUT / "00_Methods-Digest_complete.pdf"
        shutil.copy2(full, dst)
        size, pages = info(dst)
        rows.append((dst.relative_to(OUT).as_posix(), "Complete digest: all nine stage chapters, synthesis, 99 cards, references, 99 full texts", size, pages))
    for i, s in enumerate(ORDER, start=1):
        src = BUILD / "by-stage" / f"{i}_{s}_{NAMES[s].replace(' ', '-')}.pdf"
        if src.exists() and src.stat().st_size > 0:
            dst = OUT / "by-stage" / src.name
            shutil.copy2(src, dst)
            size, pages = info(dst)
            rows.append((dst.relative_to(OUT).as_posix(), f"Stage {s}, {NAMES[s]}: chapter, cards, references and full texts of the papers of this stage", size, pages))
    lines = [
        "# Methods Digest: PDF deliverables", "",
        "Generated by `tools/package.py`. Paper numbers `[n]` are identical in every file.", "",
        "| File | Contents | Size | Pages |", "|---|---|---|---|",
    ]
    lines += [f"| `{f}` | {c} | {sz} | {pg} |" for f, c, sz, pg in rows]
    lines += [
        "", "Private use only: the full texts include copies that must not be redistributed "
        "(for example Krippendorff 2019).", "",
        "Rebuild: see `HANDOFF.md`, section 3a.", "",
    ]
    (OUT / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
